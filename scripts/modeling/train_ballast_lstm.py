@torch.no_grad()
def predict_split(
    model: nn.Module,
    arrays: dict[str, np.ndarray],
    device: torch.device,
    batch_size: int,
    residual_regression: bool,
    uv_feature_indices: tuple[int, int],
) -> tuple[np.ndarray, np.ndarray]:
    model.eval()
    n = arrays["X"].shape[0]
    future_steps = arrays["y_uv"].shape[1]
    event_count = arrays["y_event"].shape[1]
    pred_uv_scaled = np.empty((n, future_steps, 2), dtype=np.float32)
    pred_event_prob = np.empty((n, event_count), dtype=np.float32)

    for start, end in iter_slices(n, batch_size, np.random.default_rng(0), shuffle_blocks=False):
        xb = numpy_batch(arrays["X"], start, end).to(device)
        pred_uv, event_logits = model(xb)
        pred_uv = full_scaled_prediction(pred_uv, xb, residual_regression, uv_feature_indices)
        pred_uv_scaled[start:end] = pred_uv.detach().cpu().numpy().astype("float32")
        pred_event_prob[start:end] = torch.sigmoid(event_logits).detach().cpu().numpy().astype("float32")

    return pred_uv_scaled, pred_event_prob


def inverse_scale_uv(pred_uv_scaled: np.ndarray, scaler: dict) -> np.ndarray:
    target_scaler = scaler["target_uv_scaler"]
    mean = np.array(
        [target_scaler["wind_u_ms"]["mean"], target_scaler["wind_v_ms"]["mean"]],
        dtype=np.float32,
    )
    std = np.array(
        [target_scaler["wind_u_ms"]["std"], target_scaler["wind_v_ms"]["std"]],
        dtype=np.float32,
    )
    return pred_uv_scaled * std + mean


def speed_direction_from_uv(uv: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    u = uv[:, :, 0]
    v = uv[:, :, 1]
    speed = np.sqrt(u**2 + v**2)
    direction = (np.rad2deg(np.arctan2(-u, -v)) + 360.0) % 360.0
    return speed.astype("float32"), direction.astype("float32")


def circular_diff_deg(target: np.ndarray, base: np.ndarray) -> np.ndarray:
    return (target - base + 180.0) % 360.0 - 180.0


def regression_metrics(
    split: str,
    model_name: str,
    pred_uv_raw: np.ndarray,
    y_uv_raw: np.ndarray,
    y_speed_dir_raw: np.ndarray,
) -> list[dict[str, object]]:
    pred_speed, pred_dir = speed_direction_from_uv(pred_uv_raw)
    true_speed = y_speed_dir_raw[:, :, 0]
    true_dir = y_speed_dir_raw[:, :, 1]

    uv_error = pred_uv_raw - y_uv_raw
    speed_error = pred_speed - true_speed
    direction_error = circular_diff_deg(pred_dir, true_dir)

    rows: list[dict[str, object]] = []

    def build_row(scope: str, uv_err: np.ndarray, speed_err: np.ndarray, dir_err: np.ndarray) -> dict[str, object]:
        return {
            "model": model_name,
            "split": split,
            "scope": scope,
            "vector_mae_ms": float(np.mean(np.abs(uv_err))),
            "vector_rmse_ms": float(np.sqrt(np.mean(uv_err**2))),
            "speed_mae_ms": float(np.mean(np.abs(speed_err))),
            "speed_rmse_ms": float(np.sqrt(np.mean(speed_err**2))),
            "direction_mae_deg": float(np.mean(np.abs(dir_err))),
        }

    rows.append(build_row("all_future_steps", uv_error, speed_error, direction_error))
    for step in range(pred_uv_raw.shape[1]):
        rows.append(
            build_row(
                f"tplus_{(step + 1) * 10}m",
                uv_error[:, step, :],
                speed_error[:, step],
                direction_error[:, step],
            )
        )
    return rows


def binary_metrics(y_true: np.ndarray, y_pred: np.ndarray) -> dict[str, float]:
    true = y_true.astype(bool)
    pred = y_pred.astype(bool)
    tp = int(np.logical_and(true, pred).sum())
    fp = int(np.logical_and(~true, pred).sum())
    fn = int(np.logical_and(true, ~pred).sum())
    tn = int(np.logical_and(~true, ~pred).sum())
    precision = tp / (tp + fp) if (tp + fp) else 0.0
    recall = tp / (tp + fn) if (tp + fn) else 0.0
    f1 = 2 * precision * recall / (precision + recall) if (precision + recall) else 0.0
    false_alarm_rate = fp / (fp + tn) if (fp + tn) else 0.0
    return {
        "prevalence": float(true.mean()),
        "predicted_rate": float(pred.mean()),
        "precision": precision,
        "recall": recall,
        "f1": f1,
        "false_alarm_rate": false_alarm_rate,
    }


def best_f1_thresholds(y_true: np.ndarray, probs: np.ndarray) -> np.ndarray:
    thresholds = np.linspace(0.05, 0.95, 19, dtype=np.float32)
    selected = np.empty(probs.shape[1], dtype=np.float32)
    for col in range(probs.shape[1]):
        best_threshold = 0.5
        best_score = -1.0
        for threshold in thresholds:
            metrics = binary_metrics(y_true[:, col], probs[:, col] >= threshold)
            if metrics["f1"] > best_score:
                best_score = metrics["f1"]
                best_threshold = float(threshold)
        selected[col] = best_threshold
    return selected


def event_metrics(
    split: str,
    model_name: str,
    y_true: np.ndarray,
    probs: np.ndarray,
    thresholds: np.ndarray,
    event_names: list[str],
) -> list[dict[str, object]]:
    rows = []
    for idx, event_name in enumerate(event_names):
        pred = probs[:, idx] >= thresholds[idx]
        rows.append(
            {
                "model": model_name,
                "split": split,
                "event": event_name,
                "threshold": float(thresholds[idx]),
                **binary_metrics(y_true[:, idx], pred),
            }
        )
    return rows


def shape_checks(arrays: dict[str, dict[str, np.ndarray]], metadata: dict) -> None:
    expected_history = metadata["history_steps"]
    expected_future = metadata["future_steps"]
    expected_features = len(metadata["feature_columns"])
    expected_events = len(metadata["event_columns"])
    for split, split_arrays in arrays.items():
        x = split_arrays["X"]
        y_uv = split_arrays["y_uv"]
        y_event = split_arrays["y_event"]
        if x.ndim != 3 or x.shape[1:] != (expected_history, expected_features):
            raise SystemExit(f"Unexpected X shape for {split}: {x.shape}")
        if y_uv.ndim != 3 or y_uv.shape[1:] != (expected_future, 2):
            raise SystemExit(f"Unexpected y_uv shape for {split}: {y_uv.shape}")
        if y_event.ndim != 2 or y_event.shape[1] != expected_events:
            raise SystemExit(f"Unexpected y_event shape for {split}: {y_event.shape}")
        if x.shape[0] != y_uv.shape[0] or x.shape[0] != y_event.shape[0]:
            raise SystemExit(f"Sample count mismatch for {split}")
        if not np.isfinite(np.asarray(x[: min(1024, len(x))])).all():
            raise SystemExit(f"Non-finite X values found in {split} preview.")


def uv_feature_indices(metadata: dict) -> tuple[int, int]:
    feature_columns = metadata["feature_columns"]
    try:
        return feature_columns.index("wind_u_ms"), feature_columns.index("wind_v_ms")
    except ValueError as exc:
        raise SystemExit("Residual regression requires wind_u_ms and wind_v_ms input features.") from exc


def target_uv_tensors(scaler: dict, device: torch.device) -> tuple[torch.Tensor, torch.Tensor]:
    target_scaler = scaler["target_uv_scaler"]
    mean = torch.tensor(
        [target_scaler["wind_u_ms"]["mean"], target_scaler["wind_v_ms"]["mean"]],
        dtype=torch.float32,
        device=device,
    ).view(1, 1, 2)
    std = torch.tensor(
        [target_scaler["wind_u_ms"]["std"], target_scaler["wind_v_ms"]["std"]],
        dtype=torch.float32,
        device=device,
    ).view(1, 1, 2)
    return mean, std


def main() -> None:
    args = parse_args()
    args.output_dir.mkdir(parents=True, exist_ok=True)
    device = choose_device(args.device)
    torch.set_num_threads(args.threads)
    set_seed(args.seed)

    arrays, metadata, scaler = load_dataset(args.dataset_dir)
    shape_checks(arrays, metadata)

    input_size = arrays["train"]["X"].shape[2]
    future_steps = arrays["train"]["y_uv"].shape[1]
    event_count = arrays["train"]["y_event"].shape[1]
    uv_indices = uv_feature_indices(metadata)
    target_uv_mean, target_uv_std = target_uv_tensors(scaler, device)
    model = WindRNN(
        input_size=input_size,
        hidden_size=args.hidden_size,
        future_steps=future_steps,
        event_count=event_count,
        num_layers=args.num_layers,
        dropout=args.dropout,
        model_type=args.model_type,
    ).to(device)

    pos_weight = torch.tensor(event_pos_weight(arrays["train"]["y_event"]), dtype=torch.float32, device=device)
    regression_loss_fn = nn.MSELoss()
    event_loss_fn = nn.BCEWithLogitsLoss(pos_weight=pos_weight)
    optimizer = torch.optim.AdamW(model.parameters(), lr=args.learning_rate, weight_decay=args.weight_decay)
    scheduler = torch.optim.lr_scheduler.ReduceLROnPlateau(
        optimizer,
        mode="min",
        factor=args.lr_factor,
        patience=args.lr_patience,
    )

    config = TrainConfig(
        dataset_dir=str(args.dataset_dir),
        output_dir=str(args.output_dir),
        epochs=args.epochs,
        batch_size=args.batch_size,
        hidden_size=args.hidden_size,
        num_layers=args.num_layers,
        dropout=args.dropout,
        learning_rate=args.learning_rate,
        weight_decay=args.weight_decay,
        event_loss_weight=args.event_loss_weight,
        direction_loss_weight=args.direction_loss_weight,
        patience=args.patience,
        lr_patience=args.lr_patience,
        lr_factor=args.lr_factor,
        seed=args.seed,
        threads=args.threads,
        shuffle_blocks=not args.no_shuffle_blocks,
        threshold_mode=args.threshold_mode,
        residual_regression=args.residual_regression,
        model_type=args.model_type,
        device=str(device),
    )
    (args.output_dir / "lstm_config.json").write_text(
        json.dumps(
            {
                **asdict(config),
                "input_size": input_size,
                "future_steps": future_steps,
                "event_count": event_count,
                "event_pos_weight": [float(x) for x in pos_weight.detach().cpu().numpy()],
                "metadata_source": str(args.dataset_dir / "metadata.json"),
                "torch_version": torch.__version__,
                "uv_feature_indices": list(uv_indices),
                "parameter_count": sum(p.numel() for p in model.parameters() if p.requires_grad),
            },
            ensure_ascii=False,
            indent=2,
        ),
        encoding="utf-8",
    )

    print(f"Device: {device}")
    print(f"Train samples: {arrays['train']['X'].shape[0]}")
    print(f"Validation samples: {arrays['validation']['X'].shape[0]}")
    print(f"Test samples: {arrays['test']['X'].shape[0]}")
    print(f"Input shape: history={metadata['history_steps']} features={input_size}")
    print(f"Output shape: future={future_steps} uv=2 events={event_count}")
    print(f"Model: {args.model_type} layers={args.num_layers} hidden={args.hidden_size}")
    print(f"Trainable parameters: {sum(p.numel() for p in model.parameters() if p.requires_grad)}")

    history_rows = []
    best_val_loss = math.inf
    best_epoch = -1
    stale_epochs = 0
    rng = np.random.default_rng(args.seed)

    for epoch in range(1, args.epochs + 1):
        train_metrics = train_one_epoch(
            model,
            arrays["train"],
            optimizer,
            regression_loss_fn,
            event_loss_fn,
            device,
            args.batch_size,
            args.event_loss_weight,
            args.direction_loss_weight,
            rng,
            shuffle_blocks=not args.no_shuffle_blocks,
            residual_regression=args.residual_regression,
            uv_feature_indices=uv_indices,
            target_uv_mean=target_uv_mean,
            target_uv_std=target_uv_std,
        )
        val_metrics = evaluate_loss(
            model,
            arrays["validation"],
            regression_loss_fn,
            event_loss_fn,
            device,
            args.batch_size,
            args.event_loss_weight,
            args.direction_loss_weight,
            residual_regression=args.residual_regression,
            uv_feature_indices=uv_indices,
            target_uv_mean=target_uv_mean,
            target_uv_std=target_uv_std,
        )
        current_lr = float(optimizer.param_groups[0]["lr"])
        row = {
            "epoch": epoch,
            "learning_rate": current_lr,
            **{f"train_{k}": v for k, v in train_metrics.items()},
            **{f"validation_{k}": v for k, v in val_metrics.items()},
        }
        history_rows.append(row)
        pd.DataFrame(history_rows).to_csv(args.output_dir / "lstm_training_history.csv", index=False)
        print(
            "epoch={epoch} lr={lr:.6g} train_loss={train_loss:.6f} val_loss={val_loss:.6f} "
            "train_reg={train_reg:.6f} val_reg={val_reg:.6f} "
            "train_event={train_event:.6f} val_event={val_event:.6f} "
            "train_dir={train_dir:.6f} val_dir={val_dir:.6f}".format(
                epoch=epoch,
                lr=current_lr,
                train_loss=train_metrics["loss"],
                val_loss=val_metrics["loss"],
                train_reg=train_metrics["regression_loss"],
                val_reg=val_metrics["regression_loss"],
                train_event=train_metrics["event_loss"],
                val_event=val_metrics["event_loss"],
                train_dir=train_metrics["direction_loss"],
                val_dir=val_metrics["direction_loss"],
            ),
            flush=True,
        )

        if val_metrics["loss"] < best_val_loss:
            best_val_loss = val_metrics["loss"]
            best_epoch = epoch
            stale_epochs = 0
            torch.save(
                {
                    "model_state_dict": model.state_dict(),
                    "config": asdict(config),
                    "metadata": metadata,
                    "best_epoch": best_epoch,
                    "best_validation_loss": best_val_loss,
                },
                args.output_dir / "lstm_best.pt",
            )
        else:
            stale_epochs += 1
            if stale_epochs >= args.patience:
                print(f"Early stopping after epoch {epoch}; best epoch was {best_epoch}.", flush=True)
                break
        scheduler.step(val_metrics["loss"])

    checkpoint = torch.load(args.output_dir / "lstm_best.pt", map_location=device)
    model.load_state_dict(checkpoint["model_state_dict"])

    val_pred_uv_scaled, val_event_prob = predict_split(
        model,
        arrays["validation"],
        device,
        args.batch_size,
        residual_regression=args.residual_regression,
        uv_feature_indices=uv_indices,
    )
    test_pred_uv_scaled, test_event_prob = predict_split(
        model,
        arrays["test"],
        device,
        args.batch_size,
        residual_regression=args.residual_regression,
        uv_feature_indices=uv_indices,
    )
    val_pred_uv_raw = inverse_scale_uv(val_pred_uv_scaled, scaler)
    test_pred_uv_raw = inverse_scale_uv(test_pred_uv_scaled, scaler)

    reg_rows = []
    model_name = f"{args.model_type}_dual_head"
    if args.residual_regression:
        model_name = f"residual_{model_name}"
    if args.direction_loss_weight > 0:
        model_name = f"{model_name}_direction_loss"
    reg_rows.extend(
        regression_metrics(
            "validation",
            model_name,
            val_pred_uv_raw,
            np.asarray(arrays["validation"]["y_uv_raw"]),
            np.asarray(arrays["validation"]["y_speed_dir_raw"]),
        )
    )
    reg_rows.extend(
        regression_metrics(
            "test",
            model_name,
            test_pred_uv_raw,
            np.asarray(arrays["test"]["y_uv_raw"]),
            np.asarray(arrays["test"]["y_speed_dir_raw"]),
        )
    )
    reg_metrics = pd.DataFrame(reg_rows)
    reg_metrics.to_csv(args.output_dir / "lstm_regression_metrics.csv", index=False)

    event_names = metadata["event_columns"]
    if args.threshold_mode == "best_f1":
        thresholds = best_f1_thresholds(np.asarray(arrays["validation"]["y_event"]), val_event_prob)
    else:
        thresholds = np.full(event_count, 0.5, dtype=np.float32)
    event_rows = []
    event_rows.extend(
        event_metrics(
            "validation",
            model_name,
            np.asarray(arrays["validation"]["y_event"]),
            val_event_prob,
            thresholds,
            event_names,
        )
    )
    event_rows.extend(
        event_metrics(
            "test",
            model_name,
            np.asarray(arrays["test"]["y_event"]),
            test_event_prob,
            thresholds,
            event_names,
        )
    )
    event_metrics_frame = pd.DataFrame(event_rows)
    event_metrics_frame.to_csv(args.output_dir / "lstm_event_metrics.csv", index=False)
    (args.output_dir / "lstm_event_thresholds.json").write_text(
        json.dumps(
            {
                "threshold_mode": args.threshold_mode,
                "thresholds": {name: float(thresholds[idx]) for idx, name in enumerate(event_names)},
                "selected_on": "validation",
            },
            ensure_ascii=False,
            indent=2,
        ),
        encoding="utf-8",
    )

    summary = {
        "best_epoch": best_epoch,
        "best_validation_loss": best_val_loss,
        "regression_metrics_csv": str(args.output_dir / "lstm_regression_metrics.csv"),
        "event_metrics_csv": str(args.output_dir / "lstm_event_metrics.csv"),
        "checkpoint": str(args.output_dir / "lstm_best.pt"),
    }
    (args.output_dir / "lstm_run_summary.json").write_text(
        json.dumps(summary, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )

    print("\nRegression metrics")
    print(reg_metrics.to_string(index=False))
    print("\nEvent metrics")
    print(event_metrics_frame.to_string(index=False))
    print(f"\nBest epoch: {best_epoch}; best validation loss: {best_val_loss:.6f}")


if __name__ == "__main__":
    main()
