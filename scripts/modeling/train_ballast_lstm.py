#!/usr/bin/env python3
"""Train a dual-head recurrent model for ballast-preview wind forecasting.

The model follows the dataset design in
``data/processed/wind_ml_10min/ballast_decision_dwd_helgoland``:

- input: past 12 ten-minute wind states and multi-resolution features;
- regression output: future 6-step wind-vector sequence in scaled u/v form;
- classification output: future wind-change event probabilities.

The script intentionally keeps preprocessing outside training. It uses the
existing train-only scalers and chronological splits generated by the data
preparation step, then writes metrics and checkpoints into an output folder.
"""

from __future__ import annotations

import argparse
import json
import math
import os
import random
from dataclasses import asdict, dataclass
from pathlib import Path

import numpy as np
import pandas as pd
import torch
from torch import nn


SPLITS = ["train", "validation", "test"]


@dataclass
class TrainConfig:
    dataset_dir: str
    output_dir: str
    epochs: int
    batch_size: int
    hidden_size: int
    num_layers: int
    dropout: float
    learning_rate: float
    weight_decay: float
    event_loss_weight: float
    direction_loss_weight: float
    patience: int
    lr_patience: int
    lr_factor: float
    seed: int
    threads: int
    shuffle_blocks: bool
    threshold_mode: str
    residual_regression: bool
    model_type: str
    device: str


class WindRNN(nn.Module):
    def __init__(
        self,
        input_size: int,
        hidden_size: int,
        future_steps: int,
        event_count: int,
        num_layers: int,
        dropout: float,
        model_type: str,
    ) -> None:
        super().__init__()
        recurrent_dropout = dropout if num_layers > 1 else 0.0
        self.future_steps = future_steps
        model_type = model_type.lower()
        if model_type == "lstm":
            recurrent_cls = nn.LSTM
        elif model_type == "gru":
            recurrent_cls = nn.GRU
        else:
            raise ValueError(f"Unsupported recurrent model type: {model_type}")
        self.model_type = model_type
        self.recurrent = recurrent_cls(
            input_size=input_size,
            hidden_size=hidden_size,
            num_layers=num_layers,
            dropout=recurrent_dropout,
            batch_first=True,
        )
        self.shared = nn.Sequential(
            nn.LayerNorm(hidden_size),
            nn.Linear(hidden_size, hidden_size),
            nn.ReLU(),
            nn.Dropout(dropout),
        )
        self.regression_head = nn.Linear(hidden_size, future_steps * 2)
        self.event_head = nn.Linear(hidden_size, event_count)

    def forward(self, x: torch.Tensor) -> tuple[torch.Tensor, torch.Tensor]:
        if self.model_type == "lstm":
            _, (hidden, _) = self.recurrent(x)
        else:
            _, hidden = self.recurrent(x)
        features = self.shared(hidden[-1])
        uv = self.regression_head(features).view(x.shape[0], self.future_steps, 2)
        event_logits = self.event_head(features)
        return uv, event_logits


