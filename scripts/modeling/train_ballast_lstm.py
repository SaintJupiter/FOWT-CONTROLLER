        event_loss_type=args.event_loss_type,
        focal_gamma=args.focal_gamma,
        focal_alpha=args.focal_alpha,
        horizon_prefix_steps=args.horizon_prefix_steps,
        horizon_tail_weight=args.horizon_tail_weight,
        far_hint_auxiliary_head=bool(args.far_hint_auxiliary_head),
