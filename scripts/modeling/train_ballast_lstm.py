class FocalBCEWithLogitsLoss(nn.Module):
    """Multi-label focal BCE for imbalanced wind-change events."""

    def __init__(self, gamma: float = 2.0, alpha: float = -1.0, pos_weight: torch.Tensor | None = None) -> None:
        super().__init__()
        self.gamma = float(gamma)
        self.alpha = float(alpha)
        self.register_buffer("pos_weight", pos_weight if pos_weight is not None else None)

    def forward(self, logits: torch.Tensor, targets: torch.Tensor) -> torch.Tensor:
        bce = nn.functional.binary_cross_entropy_with_logits(
            logits,
            targets,
            pos_weight=self.pos_weight,
            reduction="none",
        )
        prob = torch.sigmoid(logits)
        p_t = prob * targets + (1.0 - prob) * (1.0 - targets)
        loss = bce * (1.0 - p_t).clamp_min(1e-6).pow(self.gamma)
        if self.alpha >= 0.0:
            alpha_t = self.alpha * targets + (1.0 - self.alpha) * (1.0 - targets)
            loss = alpha_t * loss
        return loss.mean()


class HorizonWeightedMSELoss(nn.Module):
    """MSE with a heavier weight on the near-term prefix of the forecast."""

    def __init__(self, future_steps: int, prefix_steps: int, tail_weight: float) -> None:
        super().__init__()
        prefix_steps = max(0, min(int(prefix_steps), int(future_steps)))
        weights = torch.ones(future_steps, dtype=torch.float32)
        if prefix_steps < future_steps:
            weights[prefix_steps:] = float(tail_weight)
        weights = weights / weights.mean().clamp_min(1e-6)
        self.register_buffer("weights", weights.view(1, future_steps, 1))

    def forward(self, pred: torch.Tensor, target: torch.Tensor) -> torch.Tensor:
        diff = pred - target
        return ((diff * diff) * self.weights).mean()


class EventEmphasisMSELoss(nn.Module):
    """MSE where event-positive samples are upweighted in the gradient.

    Standard MSE on residual-uv targets converges to the conditional mean of the
    residual distribution, which for noisy meteorological data approximates
    persistence (i.e., the model predicts near-zero residual = "no change").
    This is observed in guard10 forecast-control attribution: LSTM b1/b0 ratios
    are nearly 1.0 (persistence-shape) while oracle b1/b0 has 0.07-11.7 range.

    Two emphasis modes:
    1. ``event_column >= 0``: use ``y_event[:, event_column]`` as event mask
       (intensification-biased — all existing labels skew toward speed-up
       events). Best when the goal is sharper detection of strong events.
    2. ``synth_relief_threshold > 0``: synthesize a relief mask on-the-fly
       from y_uv: relief = 1 iff future ANY-step wind magnitude drops below
       (1 - threshold) * current_step wind magnitude. This captures
       de-escalation events that the existing labels miss (existing labels
       have <15% overlap with strong-relief samples). Best when the goal is
       to learn confident "park to save pump" signals.

    Per-sample regression weight = 1 + emphasis * mask, mean-renormalized.

    Optionally accepts a horizon weight (compatible with prefix/tail schedule).
    """

    def __init__(
        self,
        future_steps: int,
        emphasis: float,
        event_column: int,
        prefix_steps: int = 0,
        tail_weight: float = 1.0,
        synth_relief_threshold: float = 0.0,
        synth_relief_current_min_ms: float = 4.0,
        synth_intensify_threshold: float = 0.0,
        synth_intensify_current_min_ms: float = 4.0,
        synth_intensify_start_step: int = 6,
        target_uv_mean: tuple[float, float] | None = None,
        target_uv_std: tuple[float, float] | None = None,
    ) -> None:
        super().__init__()
        self.emphasis = float(emphasis)
        self.event_column = int(event_column)
        self.synth_relief_threshold = float(synth_relief_threshold)
        self.synth_relief_current_min_ms = float(synth_relief_current_min_ms)
        self.synth_intensify_threshold = float(synth_intensify_threshold)
        self.synth_intensify_current_min_ms = float(synth_intensify_current_min_ms)
        self.synth_intensify_start_step = max(0, int(synth_intensify_start_step))
        prefix_steps = max(0, min(int(prefix_steps), int(future_steps)))
        h_weights = torch.ones(future_steps, dtype=torch.float32)
        if prefix_steps < future_steps:
            h_weights[prefix_steps:] = float(tail_weight)
        h_weights = h_weights / h_weights.mean().clamp_min(1e-6)
        self.register_buffer("horizon_weights", h_weights.view(1, future_steps, 1))
        if target_uv_mean is not None and target_uv_std is not None:
            self.register_buffer(
                "target_uv_mean",
                torch.tensor(target_uv_mean, dtype=torch.float32).view(1, 1, 2),
            )
            self.register_buffer(
                "target_uv_std",
                torch.tensor(target_uv_std, dtype=torch.float32).view(1, 1, 2),
            )
            self._has_denorm = True
        else:
            self._has_denorm = False

    def _compute_relief_mask(
        self, y_uv: torch.Tensor, current_uv: torch.Tensor
    ) -> torch.Tensor:
        """Compute per-sample relief mask from raw (denormalized) wind UV.

        relief = 1 iff future_min_speed < (1 - threshold) * current_speed AND
                current_speed > synth_relief_current_min_ms.
        Inputs y_uv and current_uv are expected in the same (normalized)
        space the model trains on; we denormalize using stored target stats.
        """
        if not self._has_denorm:
            # Without scaler info we cannot reliably synthesize, fall back to zero mask
            return torch.zeros(y_uv.shape[0], dtype=torch.float32, device=y_uv.device)
        y_raw = y_uv * self.target_uv_std + self.target_uv_mean
        c_raw = current_uv * self.target_uv_std + self.target_uv_mean
        fut_speed = torch.linalg.vector_norm(y_raw, dim=-1)  # (B, T)
        cur_speed = torch.linalg.vector_norm(c_raw, dim=-1).squeeze(-1)  # (B,)
        fut_min = fut_speed.min(dim=1).values  # (B,)
        threshold_factor = 1.0 - self.synth_relief_threshold
        relief = (fut_min < cur_speed * threshold_factor) & (
            cur_speed > self.synth_relief_current_min_ms
        )
        return relief.float()

    def _compute_intensify_mask(
        self, y_uv: torch.Tensor, current_uv: torch.Tensor
    ) -> torch.Tensor:
        """Compute per-sample far-horizon intensification mask from raw UV.

        This is intentionally independent from the relief mask. It targets
        60-120min hidden intensification / re-intensification samples: far
        future wind speed rises clearly above either current speed or the
        near-horizon minimum after an initial lull.
        """
        if not self._has_denorm:
            return torch.zeros(y_uv.shape[0], dtype=torch.float32, device=y_uv.device)
        y_raw = y_uv * self.target_uv_std + self.target_uv_mean
        c_raw = current_uv * self.target_uv_std + self.target_uv_mean
        fut_speed = torch.linalg.vector_norm(y_raw, dim=-1)  # (B, T)
        cur_speed = torch.linalg.vector_norm(c_raw, dim=-1).squeeze(-1)  # (B,)
        start = min(max(self.synth_intensify_start_step, 0), fut_speed.shape[1] - 1)
        far = fut_speed[:, start:]
        near = fut_speed[:, : max(start, 1)]
        far_max = far.max(dim=1).values
        near_min = near.min(dim=1).values
        threshold_factor = 1.0 + self.synth_intensify_threshold
        direct_intensify = far_max > cur_speed * threshold_factor
        re_intensify = far_max > near_min.clamp_min(1e-3) * threshold_factor
        mask = (direct_intensify | re_intensify) & (
            cur_speed > self.synth_intensify_current_min_ms
        )
        return mask.float()

    def forward(
        self,
        pred: torch.Tensor,
        target: torch.Tensor,
        y_event: torch.Tensor,
        y_uv: torch.Tensor | None = None,
        current_uv: torch.Tensor | None = None,
    ) -> torch.Tensor:
        diff = pred - target
        per_sample = ((diff * diff) * self.horizon_weights).mean(dim=(1, 2))
        # Backward-compatible behavior:
        #   - synth_relief_threshold > 0:  use relief mask alone (col ignored)
        #   - synth_relief_threshold = 0:  use event_column mask
        # Combined mode (relief OR column) is OPT-IN via combine_masks=True,
        # set externally on the instance after construction. This preserves
        # bit-identical reproducibility of older training runs that used the
        # single-mask semantics (e.g., relief_e15) while still allowing the
        # combined-bimodal training without a new CLI flag in argparse hot
        # paths.
        use_relief = (
            self.synth_relief_threshold > 0.0
            and y_uv is not None
            and current_uv is not None
        )
        use_intensify = (
            self.synth_intensify_threshold > 0.0
            and y_uv is not None
            and current_uv is not None
        )
        combine = bool(getattr(self, "combine_masks", False))
        if combine and (use_relief or use_intensify):
            masks = []
            if use_relief:
                masks.append(self._compute_relief_mask(y_uv, current_uv))
            if use_intensify:
                masks.append(self._compute_intensify_mask(y_uv, current_uv))
            if not masks:
                masks.append(torch.zeros(y_event.shape[0], dtype=torch.float32, device=y_event.device))
            event_mask = torch.clamp(torch.stack(masks, dim=0).sum(dim=0), max=1.0)
            # Historical combined mode OR'd with an event-column mask.
            col = self.event_column
            if col < 0:
                col = y_event.shape[-1] + col
            col = max(0, min(col, y_event.shape[-1] - 1))
            event_mask = torch.clamp(event_mask + y_event[:, col].float(), max=1.0)
        elif use_relief:
            relief_mask = self._compute_relief_mask(y_uv, current_uv)
            event_mask = relief_mask
        elif use_intensify:
            event_mask = self._compute_intensify_mask(y_uv, current_uv)
        else:
            col = self.event_column
            if col < 0:
                col = y_event.shape[-1] + col
            col = max(0, min(col, y_event.shape[-1] - 1))
            event_mask = y_event[:, col].float()
        weight = 1.0 + self.emphasis * event_mask
        weight = weight / weight.mean().clamp_min(1e-6)
        return (per_sample * weight).mean()


class ShapePreservationMSELoss(nn.Module):
    """MSE plus block-level pressure-shape preservation loss.

    This targets the h240_f120 failure mode where true 60-120min pressure
    clearly departs from current pressure, while the learned model stays close
    to persistence. The base MSE remains active over all steps; the extra term
    only fires on blocks where the true block pressure differs from current by
    a configurable amount, with stronger weight on 60-120min blocks.
    """

    def __init__(
        self,
        future_steps: int,
        shape_weight: float,
        delta_threshold_norm: float,
        far_start_step: int,
        far_block_weight: float,
        direction_weight: float,
        direction_margin_norm: float,
        residual_regression: bool,
        prefix_steps: int = 0,
        tail_weight: float = 1.0,
        target_uv_mean: tuple[float, float] | None = None,
        target_uv_std: tuple[float, float] | None = None,
    ) -> None:
        super().__init__()
        self.shape_weight = float(shape_weight)
        self.delta_threshold_norm = float(delta_threshold_norm)
        self.far_start_step = max(0, int(far_start_step))
        self.far_block_weight = float(far_block_weight)
        self.direction_weight = float(direction_weight)
        self.direction_margin_norm = float(direction_margin_norm)
        self.residual_regression = bool(residual_regression)
        self.future_steps = int(future_steps)
        prefix_steps = max(0, min(int(prefix_steps), int(future_steps)))
        h_weights = torch.ones(future_steps, dtype=torch.float32)
        if prefix_steps < future_steps:
            h_weights[prefix_steps:] = float(tail_weight)
        h_weights = h_weights / h_weights.mean().clamp_min(1e-6)
        self.register_buffer("horizon_weights", h_weights.view(1, future_steps, 1))
        block_count = max(1, int(math.ceil(float(future_steps) / 2.0)))
        b_weights = torch.ones(block_count, dtype=torch.float32)
        far_start_block = min(block_count, max(0, int(self.far_start_step // 2)))
        if far_start_block < block_count:
            b_weights[far_start_block:] = self.far_block_weight
        b_weights = b_weights / b_weights.mean().clamp_min(1e-6)
        self.register_buffer("block_weights", b_weights.view(1, block_count))
        if target_uv_mean is not None and target_uv_std is not None:
            self.register_buffer(
                "target_uv_mean",
                torch.tensor(target_uv_mean, dtype=torch.float32).view(1, 1, 2),
            )
            self.register_buffer(
                "target_uv_std",
                torch.tensor(target_uv_std, dtype=torch.float32).view(1, 1, 2),
            )
            self._has_denorm = True
        else:
            self._has_denorm = False

    @staticmethod
    def _block_pressure_norm(raw_uv: torch.Tensor) -> torch.Tensor:
        """Differentiable planner-like pressure norm by 20min block."""
        blocks = []
        for start in range(0, raw_uv.shape[1], 2):
            block = raw_uv[:, start : min(start + 2, raw_uv.shape[1]), :]
            speed = torch.linalg.vector_norm(block, dim=-1)
            mean_speed = speed.mean(dim=1)
            pressure = (mean_speed.clamp_min(0.0) / 12.0).pow(2).clamp(0.0, 1.5)
            blocks.append(pressure)
        return torch.stack(blocks, dim=1)

    def forward(
        self,
        pred: torch.Tensor,
        target: torch.Tensor,
        y_event: torch.Tensor,
        y_uv: torch.Tensor | None = None,
        current_uv: torch.Tensor | None = None,
    ) -> torch.Tensor:
        diff = pred - target
        base = ((diff * diff) * self.horizon_weights).mean()
        if (
            self.shape_weight <= 0.0
            or not self._has_denorm
            or y_uv is None
            or current_uv is None
        ):
            return base

        pred_full = pred + current_uv if self.residual_regression else pred
        pred_raw = pred_full * self.target_uv_std + self.target_uv_mean
        true_raw = y_uv * self.target_uv_std + self.target_uv_mean
        current_raw = current_uv * self.target_uv_std + self.target_uv_mean

        pred_pressure = self._block_pressure_norm(pred_raw)
        true_pressure = self._block_pressure_norm(true_raw)
        cur_speed = torch.linalg.vector_norm(current_raw.squeeze(1), dim=-1)
        cur_pressure = (cur_speed.clamp_min(0.0) / 12.0).pow(2).clamp(0.0, 1.5).unsqueeze(1)

        true_delta = true_pressure - cur_pressure
        pred_delta = pred_pressure - cur_pressure
        mask = (true_delta.abs() >= self.delta_threshold_norm).float()
        weights = mask * self.block_weights[:, : true_delta.shape[1]]
        denom = weights.sum().clamp_min(1.0)
        shape_loss = (((pred_delta - true_delta).pow(2)) * weights).sum() / denom
        direction_sign = true_delta.sign()
        aligned = direction_sign * pred_delta
        direction_loss = (
            torch.relu(self.direction_margin_norm - aligned).pow(2) * weights
        ).sum() / denom
        return base + self.shape_weight * (shape_loss + self.direction_weight * direction_loss)


class PressureShapeSupervisionLoss(nn.Module):
    """Planner-readable pressure-shape supervision on the UV regression output.

    Unlike a side auxiliary classifier, this loss is applied to the predicted
    UV trajectory after converting it into the same 20min pressure proxy used
    by far-horizon attribution. The intent is to make the regression output
    itself carry far-horizon relief/intensification/timing shape.
    """

    def __init__(
        self,
        future_steps: int,
        shape_weight: float,
        delta_threshold_norm: float,
        far_block_weight: float,
        event_weight: float,
        direction_weight: float,
        margin_weight: float,
        timing_weight: float,
        direction_margin_norm: float,
        residual_regression: bool,
        prefix_steps: int = 0,
        tail_weight: float = 1.0,
        target_uv_mean: tuple[float, float] | None = None,
        target_uv_std: tuple[float, float] | None = None,
    ) -> None:
        super().__init__()
        self.shape_weight = float(shape_weight)
        self.delta_threshold_norm = float(delta_threshold_norm)
        self.far_block_weight = float(far_block_weight)
        self.event_weight = float(event_weight)
        self.direction_weight = float(direction_weight)
        self.margin_weight = float(margin_weight)
        self.timing_weight = float(timing_weight)
        self.direction_margin_norm = float(direction_margin_norm)
        self.residual_regression = bool(residual_regression)
        self.future_steps = int(future_steps)
        prefix_steps = max(0, min(int(prefix_steps), int(future_steps)))
        h_weights = torch.ones(future_steps, dtype=torch.float32)
        if prefix_steps < future_steps:
            h_weights[prefix_steps:] = float(tail_weight)
        h_weights = h_weights / h_weights.mean().clamp_min(1e-6)
        self.register_buffer("horizon_weights", h_weights.view(1, future_steps, 1))
        block_count = max(1, int(math.ceil(float(future_steps) / 2.0)))
        block_weights = torch.ones(block_count, dtype=torch.float32)
        if block_count > 3:
            block_weights[3:] = self.far_block_weight
        block_weights = block_weights / block_weights.mean().clamp_min(1e-6)
        self.register_buffer("block_weights", block_weights.view(1, block_count))
        if target_uv_mean is not None and target_uv_std is not None:
            self.register_buffer(
                "target_uv_mean",
                torch.tensor(target_uv_mean, dtype=torch.float32).view(1, 1, 2),
            )
            self.register_buffer(
                "target_uv_std",
                torch.tensor(target_uv_std, dtype=torch.float32).view(1, 1, 2),
            )
            self._has_denorm = True
        else:
            self._has_denorm = False

    @staticmethod
    def _pressure_vecs(raw_uv: torch.Tensor) -> tuple[torch.Tensor, torch.Tensor]:
        vecs = []
        norms = []
        for start in range(0, raw_uv.shape[1], 2):
            block = raw_uv[:, start : min(start + 2, raw_uv.shape[1]), :]
            speed = torch.linalg.vector_norm(block, dim=-1)
            mean_u = block[:, :, 0].mean(dim=1)
            mean_v = block[:, :, 1].mean(dim=1)
            mean_speed = speed.mean(dim=1)
            mean_dir = torch.atan2(-mean_u, -mean_v)
            mag = torch.clamp((torch.clamp(mean_speed, min=0.0) / 12.0).pow(2), 0.0, 1.5)
            # Matches norm_term scale after deadband normalization.
            vec = torch.stack([-mag * torch.cos(mean_dir), mag * torch.sin(mean_dir)], dim=1)
            vecs.append(vec)
            norms.append(torch.linalg.vector_norm(vec, dim=1))
        return torch.stack(norms, dim=1), torch.stack(vecs, dim=1)

    @staticmethod
    def _event_masks(norms: torch.Tensor, vecs: torch.Tensor) -> dict[str, torch.Tensor]:
        near = norms[:, :3]
        far = norms[:, 3:6]
        near_max = near.max(dim=1).values
        near_last = near[:, -1]
        far_min = far.min(dim=1).values
        far_max = far.max(dim=1).values
        hidden_relief = (
            (near_max >= 1.0)
            & (far_min <= torch.maximum(torch.full_like(near_max, 0.75), near_max - 0.35))
            & (far_min <= near_last - 0.25)
        )
        hidden_intensification = (
            (near_max <= 0.85)
            & (far_max >= 1.10)
            & (far_max >= near_max + 0.35)
        )
        v_40_60 = vecs[:, 2, :]
        v_100_120 = vecs[:, 5, :]
        dot = (v_40_60 * v_100_120).sum(dim=1)
        na = torch.linalg.vector_norm(v_40_60, dim=1)
        nb = torch.linalg.vector_norm(v_100_120, dim=1)
        cosv = dot / torch.clamp(na * nb, min=1e-9)
        dir_shift_deg = torch.rad2deg(torch.acos(torch.clamp(cosv, -1.0, 1.0)))
        reversal = (near_max >= 0.55) & (far_max >= 0.55) & (dot < 0.0)
        direction_shift = (near_max >= 0.55) & (far_max >= 0.55) & (dir_shift_deg >= 60.0)
        far_hint = hidden_relief | hidden_intensification | reversal | direction_shift
        return {
            "hidden_relief": hidden_relief,
            "hidden_intensification": hidden_intensification,
            "reversal": reversal,
            "direction_shift": direction_shift,
            "far_hint": far_hint,
        }

    def forward(
        self,
        pred: torch.Tensor,
        target: torch.Tensor,
        y_event: torch.Tensor,
        y_uv: torch.Tensor | None = None,
        current_uv: torch.Tensor | None = None,
    ) -> torch.Tensor:
        diff = pred - target
        base = ((diff * diff) * self.horizon_weights).mean()
        if (
            self.shape_weight <= 0.0
            or not self._has_denorm
            or y_uv is None
            or current_uv is None
            or pred.shape[1] < 12
        ):
            return base

        pred_full = pred + current_uv if self.residual_regression else pred
        pred_raw = pred_full * self.target_uv_std + self.target_uv_mean
        true_raw = y_uv * self.target_uv_std + self.target_uv_mean
        current_raw = current_uv * self.target_uv_std + self.target_uv_mean

        pred_norms, pred_vecs = self._pressure_vecs(pred_raw)
        true_norms, true_vecs = self._pressure_vecs(true_raw)
        cur_speed = torch.linalg.vector_norm(current_raw.squeeze(1), dim=-1)
        cur_pressure = (torch.clamp(cur_speed, min=0.0) / 12.0).pow(2).clamp(0.0, 1.5).unsqueeze(1)

        true_delta = true_norms - cur_pressure
        pred_delta = pred_norms - cur_pressure
        true_events = self._event_masks(true_norms, true_vecs)
        far_hint = true_events["far_hint"].float()
        hidden_relief = true_events["hidden_relief"].float()
        hidden_intensification = true_events["hidden_intensification"].float()
        vector_event = (true_events["reversal"] | true_events["direction_shift"]).float()

        delta_mask = (true_delta.abs() >= self.delta_threshold_norm).float()
        event_mask = far_hint.unsqueeze(1).expand_as(delta_mask)
        weights = (delta_mask + self.event_weight * event_mask) * self.block_weights[:, : true_delta.shape[1]]
        denom = weights.sum().clamp_min(1.0)
        delta_loss = ((pred_delta - true_delta).pow(2) * weights).sum() / denom

        sign = true_delta.sign()
        direction_loss = (torch.relu(self.direction_margin_norm - sign * pred_delta).pow(2) * weights).sum() / denom

        far_pred = pred_norms[:, 3:6]
        far_true = true_norms[:, 3:6]
        near_last = true_norms[:, 2]
        relief_target = far_true.min(dim=1).values
        intens_target = far_true.max(dim=1).values
        relief_pred_min = far_pred.min(dim=1).values
        intens_pred_max = far_pred.max(dim=1).values
        relief_margin = torch.relu(relief_pred_min - torch.minimum(relief_target + 0.08, near_last - 0.18)).pow(2)
        intens_margin = torch.relu(torch.maximum(intens_target - 0.08, near_last + 0.18) - intens_pred_max).pow(2)
        # For vector direction events, make the far vector depart from near-vector persistence.
        pred_dot = (pred_vecs[:, 2, :] * pred_vecs[:, 5, :]).sum(dim=1)
        true_dot = (true_vecs[:, 2, :] * true_vecs[:, 5, :]).sum(dim=1)
        vector_margin = torch.relu(0.05 - true_dot.sign() * pred_dot).pow(2)
        event_count = (hidden_relief + hidden_intensification + vector_event).sum().clamp_min(1.0)
        margin_loss = (
            relief_margin * hidden_relief
            + intens_margin * hidden_intensification
            + vector_margin * vector_event
        ).sum() / event_count

        relief_idx = far_true.argmin(dim=1)
        intens_idx = far_true.argmax(dim=1)
        relief_timing = nn.functional.cross_entropy(-far_pred, relief_idx, reduction="none")
        intens_timing = nn.functional.cross_entropy(far_pred, intens_idx, reduction="none")
        timing_count = (hidden_relief + hidden_intensification).sum().clamp_min(1.0)
        timing_loss = (
            relief_timing * hidden_relief + intens_timing * hidden_intensification
        ).sum() / timing_count

        shape = (
            delta_loss
            + self.direction_weight * direction_loss
            + self.margin_weight * margin_loss
            + self.timing_weight * timing_loss
        )
        return base + self.shape_weight * shape


class PlannerBlockShapeSupervisionLoss(nn.Module):
    """Planner-readable pressure-shape supervision on the 0-60min blocks.

    The planner's main sequence cost consumes the first three 20min pressure
    blocks (b0/b1/b2). This loss keeps the base UV regression objective, then
    adds direct pressure-proxy supervision on those three blocks so the
    regression output itself can carry action-relevant near-horizon shape.
    """

    def __init__(
        self,
        future_steps: int,
        shape_weight: float,
        delta_threshold_norm: float,
        direction_weight: float,
        range_weight: float,
        anti_persistence_weight: float,
        direction_margin_norm: float,
        range_floor_ratio: float,
        event_balance_weight: float,
        event_balance_cap: float,
        synth_relief_threshold: float,
        synth_relief_current_min_ms: float,
        residual_regression: bool,
        prefix_steps: int = 0,
        tail_weight: float = 1.0,
        target_uv_mean: tuple[float, float] | None = None,
        target_uv_std: tuple[float, float] | None = None,
    ) -> None:
        super().__init__()
        self.shape_weight = float(shape_weight)
        self.delta_threshold_norm = float(delta_threshold_norm)
        self.direction_weight = float(direction_weight)
        self.range_weight = float(range_weight)
        self.anti_persistence_weight = float(anti_persistence_weight)
        self.direction_margin_norm = float(direction_margin_norm)
        self.range_floor_ratio = float(range_floor_ratio)
        self.event_balance_weight = float(event_balance_weight)
        self.event_balance_cap = max(1.0, float(event_balance_cap))
        self.synth_relief_threshold = float(synth_relief_threshold)
        self.synth_relief_current_min_ms = float(synth_relief_current_min_ms)
        self.residual_regression = bool(residual_regression)
        prefix_steps = max(0, min(int(prefix_steps), int(future_steps)))
        h_weights = torch.ones(future_steps, dtype=torch.float32)
        if prefix_steps < future_steps:
            h_weights[prefix_steps:] = float(tail_weight)
        h_weights = h_weights / h_weights.mean().clamp_min(1e-6)
        self.register_buffer("horizon_weights", h_weights.view(1, future_steps, 1))
        if target_uv_mean is not None and target_uv_std is not None:
            self.register_buffer(
                "target_uv_mean",
                torch.tensor(target_uv_mean, dtype=torch.float32).view(1, 1, 2),
            )
            self.register_buffer(
                "target_uv_std",
                torch.tensor(target_uv_std, dtype=torch.float32).view(1, 1, 2),
            )
            self._has_denorm = True
        else:
            self._has_denorm = False

    @staticmethod
    def _block_pressure_norm(raw_uv: torch.Tensor) -> torch.Tensor:
        blocks = []
        block_count = min(3, int(math.ceil(float(raw_uv.shape[1]) / 2.0)))
        for idx in range(block_count):
            start = idx * 2
            block = raw_uv[:, start : min(start + 2, raw_uv.shape[1]), :]
            speed = torch.linalg.vector_norm(block, dim=-1)
            mean_speed = speed.mean(dim=1)
            pressure = torch.clamp((torch.clamp(mean_speed, min=0.0) / 12.0).pow(2), 0.0, 1.5)
            blocks.append(pressure)
        return torch.stack(blocks, dim=1)

    def _near_event_mask(self, true_raw: torch.Tensor, true_blocks: torch.Tensor) -> torch.Tensor:
        true_range = true_blocks.max(dim=1).values - true_blocks.min(dim=1).values
        event = true_range >= self.delta_threshold_norm
        if self.synth_relief_threshold > 0.0:
            speed = torch.linalg.vector_norm(true_raw, dim=-1)
            current_speed = speed[:, 0]
            near_steps = speed[:, : min(6, speed.shape[1])]
            near_min = near_steps.min(dim=1).values
            relief = (near_min < current_speed * (1.0 - self.synth_relief_threshold)) & (
                current_speed > self.synth_relief_current_min_ms
            )
            event = event | relief
        return event

    def _near_event_weights(self, true_raw: torch.Tensor, true_blocks: torch.Tensor) -> torch.Tensor:
        event = self._near_event_mask(true_raw, true_blocks)
        weights = 1.0 + self.event_balance_weight * event.float()
        weights = torch.clamp(weights, max=self.event_balance_cap)
        return weights / weights.mean().clamp_min(1e-6)

    def forward(
        self,
        pred: torch.Tensor,
        target: torch.Tensor,
        y_event: torch.Tensor,
        y_uv: torch.Tensor | None = None,
        current_uv: torch.Tensor | None = None,
    ) -> torch.Tensor:
        diff = pred - target
        base_per_sample = ((diff * diff) * self.horizon_weights).mean(dim=(1, 2))
        base = base_per_sample.mean()
        if (
            self.shape_weight <= 0.0
            or not self._has_denorm
            or y_uv is None
            or current_uv is None
            or pred.shape[1] < 6
        ):
            return base

        pred_full = pred + current_uv if self.residual_regression else pred
        pred_raw = pred_full * self.target_uv_std + self.target_uv_mean
        true_raw = y_uv * self.target_uv_std + self.target_uv_mean

        pred_blocks = self._block_pressure_norm(pred_raw)
        true_blocks = self._block_pressure_norm(true_raw)
        block_count = min(pred_blocks.shape[1], true_blocks.shape[1], 3)
        pred_blocks = pred_blocks[:, :block_count]
        true_blocks = true_blocks[:, :block_count]

        event_weights = self._near_event_weights(true_raw, true_blocks)
        base = (base_per_sample * event_weights).mean()
        magnitude_per_sample = nn.functional.smooth_l1_loss(
            pred_blocks,
            true_blocks,
            reduction="none",
        ).mean(dim=1)
        magnitude_loss = (magnitude_per_sample * event_weights).mean()

        if block_count >= 2:
            true_step_delta = true_blocks[:, 1:] - true_blocks[:, :-1]
            pred_step_delta = pred_blocks[:, 1:] - pred_blocks[:, :-1]
            step_mask = (true_step_delta.abs() >= self.delta_threshold_norm).float()
            step_weights = step_mask * event_weights.unsqueeze(1)
            step_denom = step_weights.sum().clamp_min(1.0)
            signed = true_step_delta.sign() * pred_step_delta
            direction_loss = (
                torch.relu(self.direction_margin_norm - signed).pow(2) * step_weights
            ).sum() / step_denom
        else:
            direction_loss = pred_blocks.new_tensor(0.0)

        true_range = true_blocks.max(dim=1).values - true_blocks.min(dim=1).values
        pred_range = pred_blocks.max(dim=1).values - pred_blocks.min(dim=1).values
        range_mask = (true_range >= self.delta_threshold_norm).float()
        range_weights = range_mask * event_weights
        range_denom = range_weights.sum().clamp_min(1.0)
        range_loss = (
            nn.functional.smooth_l1_loss(pred_range, true_range, reduction="none") * range_weights
        ).sum() / range_denom
        anti_persistence_loss = (
            torch.relu(true_range * self.range_floor_ratio - pred_range).pow(2) * range_weights
        ).sum() / range_denom

        shape = (
            magnitude_loss
            + self.direction_weight * direction_loss
            + self.range_weight * range_loss
            + self.anti_persistence_weight * anti_persistence_loss
        )
        return base + self.shape_weight * shape


def _far_hint_pressure_norms_torch(
    uv_raw: torch.Tensor,
    deadband_pitch_deg: float = 1.0,
    deadband_roll_deg: float = 0.8,
    pressure_norm_cap: float = 1.5,
    wind_ref: float = 12.0,
) -> torch.Tensor:
    """Planner-aligned 20min pressure norms from raw future u/v."""
    blocks = []
    for start in range(0, 12, 2):
        block = uv_raw[:, start : start + 2, :]
        speed = torch.linalg.vector_norm(block, dim=-1)
        mean_u = block[:, :, 0].mean(dim=1)
        mean_v = block[:, :, 1].mean(dim=1)
        mean_speed = speed.mean(dim=1)
        mean_dir = torch.atan2(-mean_u, -mean_v)
        mag = torch.clamp((torch.clamp(mean_speed, min=0.0) / wind_ref) ** 2, 0.0, pressure_norm_cap)
        raw_pitch = -deadband_pitch_deg * mag * torch.cos(mean_dir)
        raw_roll = deadband_roll_deg * mag * torch.sin(mean_dir)
        norm = torch.sqrt((raw_pitch / deadband_pitch_deg) ** 2 + (raw_roll / deadband_roll_deg) ** 2)
        blocks.append(norm)
    return torch.stack(blocks, dim=1)


def _far_hint_block_vec_torch(uv_raw: torch.Tensor, start: int) -> torch.Tensor:
    block = uv_raw[:, start : start + 2, :]
    speed = torch.linalg.vector_norm(block, dim=-1)
    mean_u = block[:, :, 0].mean(dim=1)
    mean_v = block[:, :, 1].mean(dim=1)
    mean_speed = speed.mean(dim=1)
    mean_dir = torch.atan2(-mean_u, -mean_v)
    mag = torch.clamp((torch.clamp(mean_speed, min=0.0) / 12.0) ** 2, 0.0, 1.5)
    return torch.stack([-mag * torch.cos(mean_dir), mag * torch.sin(mean_dir)], dim=1)


def far_horizon_hint_targets_torch(
    y_uv_scaled: torch.Tensor,
    target_uv_mean: torch.Tensor,
    target_uv_std: torch.Tensor,
) -> torch.Tensor:
    """Compute far_horizon_hint_any labels from true future y_uv.

    This intentionally matches the far-horizon audit/controller hint definition:
    hidden relief OR hidden intensification OR vector reversal OR direction shift.
    sign_flip remains a diagnostic label and is not included here.
    """
    y_raw = y_uv_scaled * target_uv_std + target_uv_mean
    norms = _far_hint_pressure_norms_torch(y_raw)
    near = norms[:, :3]
    far = norms[:, 3:6]
    near_max = near.max(dim=1).values
    near_last = near[:, -1]
    far_min = far.min(dim=1).values
    far_max = far.max(dim=1).values
    hidden_relief = (
        (near_max >= 1.0)
        & (far_min <= torch.maximum(torch.full_like(near_max, 0.75), near_max - 0.35))
        & (far_min <= near_last - 0.25)
    )
    hidden_intensification = (
        (near_max <= 0.85)
        & (far_max >= 1.10)
        & (far_max >= near_max + 0.35)
    )
    vec_40_60 = _far_hint_block_vec_torch(y_raw, 4)
    vec_100_120 = _far_hint_block_vec_torch(y_raw, 10)
    dot_60_120 = (vec_40_60 * vec_100_120).sum(dim=1)
    norm_a = torch.linalg.vector_norm(vec_40_60, dim=1)
    norm_b = torch.linalg.vector_norm(vec_100_120, dim=1)
    cosv = dot_60_120 / torch.clamp(norm_a * norm_b, min=1e-9)
    dir_shift_deg = torch.rad2deg(torch.acos(torch.clamp(cosv, -1.0, 1.0)))
    reversal = (near_max >= 0.55) & (far_max >= 0.55) & (dot_60_120 < 0.0)
    direction_shift = (near_max >= 0.55) & (far_max >= 0.55) & (dir_shift_deg >= 60.0)
    return (hidden_relief | hidden_intensification | reversal | direction_shift).float()


def far_horizon_hint_targets_np(y_uv_scaled: np.ndarray, scaler: dict) -> np.ndarray:
    target_scaler = scaler["target_uv_scaler"]
    mean = torch.tensor(
        [target_scaler["wind_u_ms"]["mean"], target_scaler["wind_v_ms"]["mean"]],
        dtype=torch.float32,
    ).view(1, 1, 2)
    std = torch.tensor(
        [target_scaler["wind_u_ms"]["std"], target_scaler["wind_v_ms"]["std"]],
        dtype=torch.float32,
    ).view(1, 1, 2)
    rows: list[np.ndarray] = []
    for start in range(0, y_uv_scaled.shape[0], 20000):
        batch_np = np.array(y_uv_scaled[start : start + 20000], dtype=np.float32, copy=True)
        batch = torch.from_numpy(batch_np)
        rows.append(far_horizon_hint_targets_torch(batch, mean, std).numpy().astype(np.float32))
    return np.concatenate(rows, axis=0)


class SimpleAdamW:
    """Small AdamW fallback that avoids importing ``torch.optim``.

    PyTorch 2.11 on the local Python 3.12/MPS environment can stall while
    lazily importing the optimizer stack. This class intentionally implements
    only the tiny subset the training loop uses: ``zero_grad()``, ``step()``,
    and ``param_groups[0]["lr"]`` for scheduler/reporting.
    """

    def __init__(
        self,
        params,
        lr: float,
        weight_decay: float,
        betas: tuple[float, float] = (0.9, 0.999),
        eps: float = 1e-8,
    ) -> None:
        self.params = [p for p in params if p.requires_grad]
        self.param_groups = [{"lr": float(lr)}]
        self.weight_decay = float(weight_decay)
        self.beta1 = float(betas[0])
        self.beta2 = float(betas[1])
        self.eps = float(eps)
        self._step = 0
        self._state: dict[int, tuple[torch.Tensor, torch.Tensor]] = {}

    def zero_grad(self, set_to_none: bool = True) -> None:
        for param in self.params:
            if param.grad is None:
                continue
            if set_to_none:
                param.grad = None
            else:
                param.grad.zero_()

    @torch.no_grad()
    def step(self) -> None:
        self._step += 1
        lr = float(self.param_groups[0]["lr"])
        bias_correction1 = 1.0 - self.beta1 ** self._step
        bias_correction2 = 1.0 - self.beta2 ** self._step
        step_size = lr * math.sqrt(bias_correction2) / max(bias_correction1, 1e-12)
        for param in self.params:
            grad = param.grad
            if grad is None:
                continue
            if self.weight_decay:
                param.mul_(1.0 - lr * self.weight_decay)
            key = id(param)
            if key not in self._state:
                self._state[key] = (torch.zeros_like(param), torch.zeros_like(param))
            exp_avg, exp_avg_sq = self._state[key]
            exp_avg.mul_(self.beta1).add_(grad, alpha=1.0 - self.beta1)
            exp_avg_sq.mul_(self.beta2).addcmul_(grad, grad, value=1.0 - self.beta2)
            denom = exp_avg_sq.sqrt().add_(self.eps)
            param.addcdiv_(exp_avg, denom, value=-step_size)


class SimpleReduceLROnPlateau:
    """Minimal ReduceLROnPlateau fallback for ``SimpleAdamW``."""

    def __init__(self, optimizer: SimpleAdamW, factor: float, patience: int) -> None:
        self.optimizer = optimizer
        self.factor = float(factor)
        self.patience = max(0, int(patience))
        self.best = math.inf
        self.bad_epochs = 0

    def step(self, value: float) -> None:
        value = float(value)
        if value < self.best:
            self.best = value
            self.bad_epochs = 0
            return
        self.bad_epochs += 1
        if self.bad_epochs > self.patience:
            self.optimizer.param_groups[0]["lr"] *= self.factor
            self.bad_epochs = 0


class WindRNN(nn.Module):
    def __init__(
        self,
        input_size: int,
        hidden_size: int,
        future_steps: int,
        event_count: int,
        num_layers: int,
        dropout: float,
        model_type: str,
        far_hint_head: bool = False,
    ) -> None:
        super().__init__()
        recurrent_dropout = dropout if num_layers > 1 else 0.0
        self.future_steps = future_steps
        model_type = model_type.lower()
        if model_type == "lstm":
            recurrent_cls = nn.LSTM
        elif model_type == "gru":
            recurrent_cls = nn.GRU
        else:
            raise ValueError(f"Unsupported recurrent model type: {model_type}")
        self.model_type = model_type
        self.recurrent = recurrent_cls(
            input_size=input_size,
            hidden_size=hidden_size,
            num_layers=num_layers,
            dropout=recurrent_dropout,
            batch_first=True,
        )
        self.shared = nn.Sequential(
            nn.LayerNorm(hidden_size),
            nn.Linear(hidden_size, hidden_size),
            nn.ReLU(),
            nn.Dropout(dropout),
        )
        self.regression_head = nn.Linear(hidden_size, future_steps * 2)
        self.event_head = nn.Linear(hidden_size, event_count)
        self.far_hint_head = nn.Linear(hidden_size, 1) if far_hint_head else None

    def _features(self, x: torch.Tensor) -> torch.Tensor:
        if self.model_type == "lstm":
            _, (hidden, _) = self.recurrent(x)
        else:
            _, hidden = self.recurrent(x)
        return self.shared(hidden[-1])

    def forward(self, x: torch.Tensor) -> tuple[torch.Tensor, torch.Tensor]:
        features = self._features(x)
        uv = self.regression_head(features).view(x.shape[0], self.future_steps, 2)
        event_logits = self.event_head(features)
        return uv, event_logits

    def forward_with_aux(self, x: torch.Tensor) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor | None]:
        features = self._features(x)
        uv = self.regression_head(features).view(x.shape[0], self.future_steps, 2)
        event_logits = self.event_head(features)
        far_hint_logits = self.far_hint_head(features).view(-1) if self.far_hint_head is not None else None
        return uv, event_logits, far_hint_logits


class CNNGRU(nn.Module):
    def __init__(
        self,
        input_size: int,
        hidden_size: int,
        future_steps: int,
        event_count: int,
        num_layers: int,
        dropout: float,
        conv_kernel_size: int,
    ) -> None:
        super().__init__()
        if conv_kernel_size % 2 == 0:
            raise ValueError("conv_kernel_size must be odd to keep sequence length stable.")
        self.future_steps = future_steps
        self.conv = nn.Sequential(
            nn.Conv1d(input_size, hidden_size, kernel_size=conv_kernel_size, padding=conv_kernel_size // 2),
            nn.BatchNorm1d(hidden_size),
            nn.ReLU(),
            nn.Dropout(dropout),
        )
        self.recurrent = nn.GRU(
            input_size=hidden_size,
            hidden_size=hidden_size,
            num_layers=num_layers,
            dropout=dropout if num_layers > 1 else 0.0,
            batch_first=True,
        )
        self.shared = nn.Sequential(
            nn.LayerNorm(hidden_size),
            nn.Linear(hidden_size, hidden_size),
            nn.ReLU(),
            nn.Dropout(dropout),
        )
        self.regression_head = nn.Linear(hidden_size, future_steps * 2)
        self.event_head = nn.Linear(hidden_size, event_count)

    def forward(self, x: torch.Tensor) -> tuple[torch.Tensor, torch.Tensor]:
        z = self.conv(x.transpose(1, 2)).transpose(1, 2)
        _, hidden = self.recurrent(z)
        features = self.shared(hidden[-1])
        uv = self.regression_head(features).view(x.shape[0], self.future_steps, 2)
        event_logits = self.event_head(features)
        return uv, event_logits


class TemporalAttentionPool(nn.Module):
    def __init__(self, hidden_size: int, dropout: float) -> None:
        super().__init__()
        self.score = nn.Sequential(
            nn.Linear(hidden_size, hidden_size),
            nn.Tanh(),
            nn.Dropout(dropout),
            nn.Linear(hidden_size, 1),
        )

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        weights = self.score(x).squeeze(-1)
        weights = torch.softmax(weights, dim=1)
        return torch.sum(x * weights.unsqueeze(-1), dim=1)


class MultiScaleConvStem(nn.Module):
    def __init__(self, input_size: int, hidden_size: int, dropout: float, base_kernel_size: int) -> None:
        super().__init__()
        kernels = []
        for kernel_size in (base_kernel_size, base_kernel_size + 2, base_kernel_size + 4):
            if kernel_size % 2 == 0:
                kernel_size += 1
            if kernel_size not in kernels:
                kernels.append(kernel_size)
        self.branches = nn.ModuleList(
            [
                nn.Sequential(
                    nn.Conv1d(input_size, hidden_size, kernel_size=kernel_size, padding=kernel_size // 2),
                    nn.BatchNorm1d(hidden_size),
                    nn.GELU(),
                    nn.Dropout(dropout),
                )
                for kernel_size in kernels
            ]
        )
        self.fuse = nn.Sequential(
            nn.Conv1d(hidden_size * len(self.branches), hidden_size, kernel_size=1),
            nn.BatchNorm1d(hidden_size),
            nn.GELU(),
            nn.Dropout(dropout),
        )
        self.residual = nn.Sequential(
            nn.Conv1d(input_size, hidden_size, kernel_size=1),
            nn.BatchNorm1d(hidden_size),
        )
        self.output_norm = nn.LayerNorm(hidden_size)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        z = x.transpose(1, 2)
        branches = [branch(z) for branch in self.branches]
        fused = self.fuse(torch.cat(branches, dim=1)) + self.residual(z)
        return self.output_norm(fused.transpose(1, 2))


class MultiScaleAttnGRU(nn.Module):
    def __init__(
        self,
        input_size: int,
        hidden_size: int,
        future_steps: int,
        event_count: int,
        num_layers: int,
        dropout: float,
        conv_kernel_size: int,
    ) -> None:
        super().__init__()
        self.future_steps = future_steps
        self.stem = MultiScaleConvStem(input_size, hidden_size, dropout, conv_kernel_size)
        self.recurrent = nn.GRU(
            input_size=hidden_size,
            hidden_size=hidden_size,
            num_layers=num_layers,
            dropout=dropout if num_layers > 1 else 0.0,
            batch_first=True,
        )
        self.temporal_pool = TemporalAttentionPool(hidden_size, dropout)
        self.shared = nn.Sequential(
            nn.LayerNorm(hidden_size * 2),
            nn.Linear(hidden_size * 2, hidden_size),
            nn.GELU(),
            nn.Dropout(dropout),
            nn.Linear(hidden_size, hidden_size),
            nn.GELU(),
            nn.Dropout(dropout),
        )
        self.regression_head = nn.Linear(hidden_size, future_steps * 2)
        self.event_head = nn.Linear(hidden_size, event_count)

    def forward(self, x: torch.Tensor) -> tuple[torch.Tensor, torch.Tensor]:
        z = self.stem(x)
        seq, hidden = self.recurrent(z)
        pooled = self.temporal_pool(seq)
        features = self.shared(torch.cat([pooled, hidden[-1]], dim=-1))
        uv = self.regression_head(features).view(x.shape[0], self.future_steps, 2)
        event_logits = self.event_head(features)
        return uv, event_logits


class Chomp1d(nn.Module):
    def __init__(self, chomp_size: int) -> None:
        super().__init__()
        self.chomp_size = chomp_size

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        if self.chomp_size == 0:
            return x
        return x[:, :, : -self.chomp_size]


class TCNBlock(nn.Module):
    def __init__(self, in_channels: int, out_channels: int, kernel_size: int, dilation: int, dropout: float) -> None:
        super().__init__()
        padding = (kernel_size - 1) * dilation
        self.net = nn.Sequential(
            nn.Conv1d(in_channels, out_channels, kernel_size, padding=padding, dilation=dilation),
            Chomp1d(padding),
            nn.BatchNorm1d(out_channels),
            nn.ReLU(),
            nn.Dropout(dropout),
            nn.Conv1d(out_channels, out_channels, kernel_size, padding=padding, dilation=dilation),
            Chomp1d(padding),
            nn.BatchNorm1d(out_channels),
            nn.ReLU(),
            nn.Dropout(dropout),
        )
        self.residual = nn.Conv1d(in_channels, out_channels, 1) if in_channels != out_channels else nn.Identity()

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        return self.net(x) + self.residual(x)


class TCNForecast(nn.Module):
    def __init__(
        self,
        input_size: int,
        hidden_size: int,
        future_steps: int,
        event_count: int,
        dropout: float,
        conv_kernel_size: int,
    ) -> None:
        super().__init__()
        self.future_steps = future_steps
        channels = [input_size, hidden_size, hidden_size, hidden_size]
        dilations = [1, 2, 4]
        self.tcn = nn.Sequential(
            *[
                TCNBlock(channels[idx], channels[idx + 1], conv_kernel_size, dilations[idx], dropout)
                for idx in range(len(dilations))
            ]
        )
        self.shared = nn.Sequential(
            nn.LayerNorm(hidden_size),
            nn.Linear(hidden_size, hidden_size),
            nn.ReLU(),
            nn.Dropout(dropout),
        )
        self.regression_head = nn.Linear(hidden_size, future_steps * 2)
        self.event_head = nn.Linear(hidden_size, event_count)

    def forward(self, x: torch.Tensor) -> tuple[torch.Tensor, torch.Tensor]:
        z = self.tcn(x.transpose(1, 2)).transpose(1, 2)
        features = self.shared(z[:, -1, :])
        uv = self.regression_head(features).view(x.shape[0], self.future_steps, 2)
        event_logits = self.event_head(features)
        return uv, event_logits


def build_model(
    input_size: int,
    hidden_size: int,
    future_steps: int,
    event_count: int,
    num_layers: int,
    dropout: float,
    model_type: str,
    conv_kernel_size: int,
    far_hint_head: bool = False,
) -> nn.Module:
    model_type = model_type.lower()
    if model_type in {"lstm", "gru"}:
        return WindRNN(
            input_size=input_size,
            hidden_size=hidden_size,
            future_steps=future_steps,
            event_count=event_count,
            num_layers=num_layers,
            dropout=dropout,
            model_type=model_type,
            far_hint_head=far_hint_head,
        )
    if far_hint_head:
        raise ValueError("--far-hint-auxiliary-head currently supports --model-type lstm or gru only.")
    if model_type == "cnn_gru":
        return CNNGRU(
            input_size=input_size,
            hidden_size=hidden_size,
            future_steps=future_steps,
            event_count=event_count,
            num_layers=num_layers,
            dropout=dropout,
            conv_kernel_size=conv_kernel_size,
        )
    if model_type == "ms_attn_gru":
        return MultiScaleAttnGRU(
            input_size=input_size,
            hidden_size=hidden_size,
            future_steps=future_steps,
            event_count=event_count,
            num_layers=num_layers,
            dropout=dropout,
            conv_kernel_size=conv_kernel_size,
        )
    if model_type == "tcn":
        return TCNForecast(
            input_size=input_size,
            hidden_size=hidden_size,
            future_steps=future_steps,
            event_count=event_count,
            dropout=dropout,
            conv_kernel_size=conv_kernel_size,
        )
    raise ValueError(f"Unsupported model type: {model_type}")


