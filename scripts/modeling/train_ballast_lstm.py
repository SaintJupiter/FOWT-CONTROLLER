def choose_device(requested: str) -> torch.device:
    if requested == "auto":
        if torch.cuda.is_available():
            return torch.device("cuda")
        if torch.backends.mps.is_available():
            return torch.device("mps")
        return torch.device("cpu")
    if requested == "cuda" and not torch.cuda.is_available():
        raise SystemExit("CUDA was requested but is not available.")
    if requested == "mps" and not torch.backends.mps.is_available():
        raise SystemExit("MPS was requested but is not available.")
    return torch.device(requested)


def set_seed(seed: int) -> None:
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)


def load_arrays(dataset_dir: Path, split: str) -> dict[str, np.ndarray]:
    return {
        "X": np.load(dataset_dir / f"X_{split}.npy", mmap_mode="r"),
        "y_uv": np.load(dataset_dir / f"y_uv_{split}.npy", mmap_mode="r"),
        "y_uv_raw": np.load(dataset_dir / f"y_uv_raw_{split}.npy", mmap_mode="r"),
        "y_speed_dir_raw": np.load(dataset_dir / f"y_speed_dir_raw_{split}.npy", mmap_mode="r"),
        "y_event": np.load(dataset_dir / f"y_event_{split}.npy", mmap_mode="r"),
    }


def load_dataset(dataset_dir: Path) -> tuple[dict[str, dict[str, np.ndarray]], dict, dict]:
    metadata = json.loads((dataset_dir / "metadata.json").read_text(encoding="utf-8"))
    scaler = json.loads((dataset_dir / "scaler_train.json").read_text(encoding="utf-8"))
    arrays = {split: load_arrays(dataset_dir, split) for split in SPLITS}
    return arrays, metadata, scaler


def iter_slices(n: int, batch_size: int, rng: np.random.Generator, shuffle_blocks: bool) -> list[tuple[int, int]]:
    starts = list(range(0, n, batch_size))
    if shuffle_blocks:
        rng.shuffle(starts)
    return [(start, min(start + batch_size, n)) for start in starts]


def event_pos_weight(y_event_train: np.ndarray) -> np.ndarray:
    rates = np.asarray(y_event_train[:], dtype=np.float32).mean(axis=0)
    rates = np.clip(rates, 1e-4, 1 - 1e-4)
    weights = (1.0 - rates) / rates
    return np.clip(weights, 1.0, 50.0).astype("float32")


def numpy_batch(array: np.ndarray, start: int, end: int, dtype: np.dtype = np.float32) -> torch.Tensor:
    return torch.from_numpy(np.array(array[start:end], dtype=dtype, copy=True))


def regression_target(
    y_uv: torch.Tensor,
    x: torch.Tensor,
    residual_regression: bool,
    uv_feature_indices: tuple[int, int],
) -> torch.Tensor:
    if not residual_regression:
        return y_uv
    current_uv = x[:, -1, list(uv_feature_indices)].unsqueeze(1)
    return y_uv - current_uv


def full_scaled_prediction(
    pred_regression: torch.Tensor,
    x: torch.Tensor,
    residual_regression: bool,
    uv_feature_indices: tuple[int, int],
) -> torch.Tensor:
    if not residual_regression:
        return pred_regression
    current_uv = x[:, -1, list(uv_feature_indices)].unsqueeze(1)
    return pred_regression + current_uv


def wind_direction_loss(
    pred_regression: torch.Tensor,
    y_uv_scaled: torch.Tensor,
    x: torch.Tensor,
    residual_regression: bool,
    uv_feature_indices: tuple[int, int],
    target_uv_mean: torch.Tensor,
    target_uv_std: torch.Tensor,
) -> torch.Tensor:
    pred_scaled = full_scaled_prediction(pred_regression, x, residual_regression, uv_feature_indices)
    pred_raw = pred_scaled * target_uv_std + target_uv_mean
    true_raw = y_uv_scaled * target_uv_std + target_uv_mean

    pred_norm = torch.linalg.vector_norm(pred_raw, dim=-1).clamp_min(1e-3)
    true_norm = torch.linalg.vector_norm(true_raw, dim=-1).clamp_min(1e-3)
    cosine = (pred_raw * true_raw).sum(dim=-1) / (pred_norm * true_norm)
    angular = 1.0 - cosine.clamp(-1.0, 1.0)

    # Direction becomes physically noisy at very low wind speed; reduce its loss weight there.
    speed_weight = (true_norm / 5.0).clamp(max=1.0)
    return (angular * speed_weight).sum() / speed_weight.sum().clamp_min(1.0)


def train_one_epoch(
    model: nn.Module,
    arrays: dict[str, np.ndarray],
    optimizer: torch.optim.Optimizer,
    regression_loss_fn: nn.Module,
    event_loss_fn: nn.Module,
    device: torch.device,
    batch_size: int,
    event_loss_weight: float,
    direction_loss_weight: float,
    rng: np.random.Generator,
    shuffle_blocks: bool,
    residual_regression: bool,
    uv_feature_indices: tuple[int, int],
    target_uv_mean: torch.Tensor,
    target_uv_std: torch.Tensor,
) -> dict[str, float]:
    model.train()
    n = arrays["X"].shape[0]
    total_loss = 0.0
    total_reg = 0.0
    total_event = 0.0
    total_direction = 0.0
    total_count = 0

    for start, end in iter_slices(n, batch_size, rng, shuffle_blocks):
        xb = numpy_batch(arrays["X"], start, end).to(device)
        y_uv = numpy_batch(arrays["y_uv"], start, end).to(device)
        y_event = numpy_batch(arrays["y_event"], start, end).to(device)

        optimizer.zero_grad(set_to_none=True)
        pred_uv, event_logits = model(xb)
        y_reg = regression_target(y_uv, xb, residual_regression, uv_feature_indices)
        reg_loss = regression_loss_fn(pred_uv, y_reg)
        event_loss = event_loss_fn(event_logits, y_event)
        if direction_loss_weight > 0.0:
            direction_loss = wind_direction_loss(
                pred_uv,
                y_uv,
                xb,
                residual_regression,
                uv_feature_indices,
                target_uv_mean,
                target_uv_std,
            )
        else:
            direction_loss = pred_uv.new_tensor(0.0)
        loss = reg_loss + event_loss_weight * event_loss + direction_loss_weight * direction_loss
        loss.backward()
        nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)
        optimizer.step()

        batch_count = end - start
        total_loss += float(loss.detach().cpu()) * batch_count
        total_reg += float(reg_loss.detach().cpu()) * batch_count
        total_event += float(event_loss.detach().cpu()) * batch_count
        total_direction += float(direction_loss.detach().cpu()) * batch_count
        total_count += batch_count

    return {
        "loss": total_loss / total_count,
        "regression_loss": total_reg / total_count,
        "event_loss": total_event / total_count,
        "direction_loss": total_direction / total_count,
    }


