def iter_slices(n: int, batch_size: int, rng: np.random.Generator, shuffle_blocks: bool) -> list[tuple[int, int]]:
    starts = list(range(0, n, batch_size))
    if shuffle_blocks:
        rng.shuffle(starts)
    return [(start, min(start + batch_size, n)) for start in starts]


def event_pos_weight(y_event_train: np.ndarray) -> np.ndarray:
    rates = np.asarray(y_event_train[:], dtype=np.float32).mean(axis=0)
    rates = np.clip(rates, 1e-4, 1 - 1e-4)
    weights = (1.0 - rates) / rates
    return np.clip(weights, 1.0, 50.0).astype("float32")


def loss_mask_summary(
    arrays: dict[str, np.ndarray],
    scaler: dict,
    synth_relief_threshold: float,
    synth_relief_current_min_ms: float,
    synth_intensify_threshold: float,
    synth_intensify_current_min_ms: float,
    synth_intensify_start_step: int,
    shape_delta_threshold: float,
    shape_far_start_step: int,
    planner_block_delta_threshold: float = 0.12,
    max_samples: int | None = None,
) -> dict[str, float]:
    """Summarize true-label masks used by optional forecast-shape losses."""
    target_scaler = scaler["target_uv_scaler"]
    mean = np.array(
        [target_scaler["wind_u_ms"]["mean"], target_scaler["wind_v_ms"]["mean"]],
        dtype=np.float32,
    )
    std = np.array(
        [target_scaler["wind_u_ms"]["std"], target_scaler["wind_v_ms"]["std"]],
        dtype=np.float32,
    )
    y = arrays["y_uv"]
    n = int(y.shape[0])
    if max_samples is not None:
        n = min(n, int(max_samples))
    total = 0
    relief_count = 0
    intensify_count = 0
    shape_count = 0
    far_shape_count = 0
    planner_block_event_count = 0
    for start in range(0, n, 20000):
        end = min(start + 20000, n)
        y_raw = np.asarray(y[start:end], dtype=np.float32) * std + mean
        speed = np.linalg.norm(y_raw, axis=-1)
        current_speed = speed[:, 0]
        total += y_raw.shape[0]
        if synth_relief_threshold > 0.0:
            relief_count += int(
                (
                    (speed.min(axis=1) < current_speed * (1.0 - synth_relief_threshold))
                    & (current_speed > synth_relief_current_min_ms)
                ).sum()
            )
        blocks = np.stack(
            [speed[:, idx : min(idx + 2, speed.shape[1])].mean(axis=1) for idx in range(0, speed.shape[1], 2)],
            axis=1,
        )
        pressure = np.clip((blocks / 12.0) ** 2, 0.0, 1.5)
        current_pressure = np.clip((current_speed / 12.0) ** 2, 0.0, 1.5)
        far_start_block = min(max(int(shape_far_start_step // 2), 0), pressure.shape[1] - 1)
        far = pressure[:, far_start_block:]
        if synth_intensify_threshold > 0.0:
            int_start_block = min(max(int(synth_intensify_start_step // 2), 0), pressure.shape[1] - 1)
            near = pressure[:, : max(int_start_block, 1)]
            int_far = pressure[:, int_start_block:]
            intensify_count += int(
                (
                    (
                        (int_far.max(axis=1) > current_pressure * (1.0 + synth_intensify_threshold))
                        | (int_far.max(axis=1) > near.min(axis=1) * (1.0 + synth_intensify_threshold))
                    )
                    & (current_speed > synth_intensify_current_min_ms)
                ).sum()
            )
        shape_mask = np.abs(pressure - current_pressure[:, None]) >= shape_delta_threshold
        shape_count += int(shape_mask.any(axis=1).sum())
        far_shape_count += int((np.abs(far - current_pressure[:, None]) >= shape_delta_threshold).any(axis=1).sum())
        near_blocks = pressure[:, : min(3, pressure.shape[1])]
        near_range = near_blocks.max(axis=1) - near_blocks.min(axis=1)
        near_delta = np.abs(np.diff(near_blocks, axis=1)) if near_blocks.shape[1] >= 2 else np.zeros((near_blocks.shape[0], 0))
        planner_block_event_count += int(
            ((near_range >= planner_block_delta_threshold) | (near_delta >= planner_block_delta_threshold).any(axis=1)).sum()
        )
    denom = max(total, 1)
    return {
        "samples": float(total),
        "synth_relief_count": float(relief_count),
        "synth_relief_rate": float(relief_count / denom),
        "synth_intensify_count": float(intensify_count),
        "synth_intensify_rate": float(intensify_count / denom),
        "shape_change_count": float(shape_count),
        "shape_change_rate": float(shape_count / denom),
        "far_shape_change_count": float(far_shape_count),
        "far_shape_change_rate": float(far_shape_count / denom),
        "planner_block_event_count": float(planner_block_event_count),
        "planner_block_event_rate": float(planner_block_event_count / denom),
    }


def numpy_batch(array: np.ndarray, start: int, end: int, dtype: np.dtype = np.float32) -> torch.Tensor:
    return torch.from_numpy(np.array(array[start:end], dtype=dtype, copy=True))


def regression_target(
    y_uv: torch.Tensor,
    x: torch.Tensor,
    residual_regression: bool,
    uv_feature_indices: tuple[int, int],
) -> torch.Tensor:
    if not residual_regression:
        return y_uv
    current_uv = x[:, -1, list(uv_feature_indices)].unsqueeze(1)
    return y_uv - current_uv


def full_scaled_prediction(
    pred_regression: torch.Tensor,
    x: torch.Tensor,
    residual_regression: bool,
    uv_feature_indices: tuple[int, int],
) -> torch.Tensor:
    if not residual_regression:
        return pred_regression
    current_uv = x[:, -1, list(uv_feature_indices)].unsqueeze(1)
    return pred_regression + current_uv


def wind_direction_loss(
    pred_regression: torch.Tensor,
    y_uv_scaled: torch.Tensor,
    x: torch.Tensor,
    residual_regression: bool,
    uv_feature_indices: tuple[int, int],
    target_uv_mean: torch.Tensor,
    target_uv_std: torch.Tensor,
) -> torch.Tensor:
    pred_scaled = full_scaled_prediction(pred_regression, x, residual_regression, uv_feature_indices)
    pred_raw = pred_scaled * target_uv_std + target_uv_mean
    true_raw = y_uv_scaled * target_uv_std + target_uv_mean

    pred_norm = torch.linalg.vector_norm(pred_raw, dim=-1).clamp_min(1e-3)
    true_norm = torch.linalg.vector_norm(true_raw, dim=-1).clamp_min(1e-3)
    cosine = (pred_raw * true_raw).sum(dim=-1) / (pred_norm * true_norm)
    angular = 1.0 - cosine.clamp(-1.0, 1.0)

    # Direction becomes physically noisy at very low wind speed; reduce its loss weight there.
    speed_weight = (true_norm / 5.0).clamp(max=1.0)
    return (angular * speed_weight).sum() / speed_weight.sum().clamp_min(1.0)


def train_one_epoch(
    model: nn.Module,
    arrays: dict[str, np.ndarray],
    optimizer: torch.optim.Optimizer,
    regression_loss_fn: nn.Module,
    event_loss_fn: nn.Module,
    device: torch.device,
    batch_size: int,
    event_loss_weight: float,
    direction_loss_weight: float,
    rng: np.random.Generator,
    shuffle_blocks: bool,
    residual_regression: bool,
    uv_feature_indices: tuple[int, int],
    target_uv_mean: torch.Tensor,
    target_uv_std: torch.Tensor,
    far_hint_loss_fn: nn.Module | None = None,
    far_hint_loss_weight: float = 0.0,
) -> dict[str, float]:
    model.train()
    n = arrays["X"].shape[0]
    total_loss = 0.0
    total_reg = 0.0
    total_event = 0.0
    total_direction = 0.0
    total_far_hint = 0.0
    total_count = 0

    for start, end in iter_slices(n, batch_size, rng, shuffle_blocks):
        xb = numpy_batch(arrays["X"], start, end).to(device)
        y_uv = numpy_batch(arrays["y_uv"], start, end).to(device)
        y_event = numpy_batch(arrays["y_event"], start, end).to(device)

        optimizer.zero_grad(set_to_none=True)
        if far_hint_loss_fn is not None and hasattr(model, "forward_with_aux"):
            pred_uv, event_logits, far_hint_logits = model.forward_with_aux(xb)
        else:
            pred_uv, event_logits = model(xb)
            far_hint_logits = None
        y_reg = regression_target(y_uv, xb, residual_regression, uv_feature_indices)
        if isinstance(
            regression_loss_fn,
            (
                EventEmphasisMSELoss,
                ShapePreservationMSELoss,
                PressureShapeSupervisionLoss,
                PlannerBlockShapeSupervisionLoss,
            ),
        ):
            cur_uv = xb[:, -1:, list(uv_feature_indices)]
            reg_loss = regression_loss_fn(pred_uv, y_reg, y_event, y_uv, cur_uv)
        else:
            reg_loss = regression_loss_fn(pred_uv, y_reg)
        event_loss = event_loss_fn(event_logits, y_event)
        if direction_loss_weight > 0.0:
            direction_loss = wind_direction_loss(
                pred_uv,
                y_uv,
                xb,
                residual_regression,
                uv_feature_indices,
                target_uv_mean,
                target_uv_std,
            )
        else:
            direction_loss = pred_uv.new_tensor(0.0)
        if far_hint_loss_fn is not None and far_hint_logits is not None and far_hint_loss_weight > 0.0:
            far_hint_target = far_horizon_hint_targets_torch(y_uv, target_uv_mean, target_uv_std)
            far_hint_loss = far_hint_loss_fn(far_hint_logits, far_hint_target)
        else:
            far_hint_loss = pred_uv.new_tensor(0.0)
        loss = (
            reg_loss
            + event_loss_weight * event_loss
            + direction_loss_weight * direction_loss
            + far_hint_loss_weight * far_hint_loss
        )
        loss.backward()
        nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)
        optimizer.step()

        batch_count = end - start
        total_loss += float(loss.detach().cpu()) * batch_count
        total_reg += float(reg_loss.detach().cpu()) * batch_count
        total_event += float(event_loss.detach().cpu()) * batch_count
        total_direction += float(direction_loss.detach().cpu()) * batch_count
        total_far_hint += float(far_hint_loss.detach().cpu()) * batch_count
        total_count += batch_count

    return {
        "loss": total_loss / total_count,
        "regression_loss": total_reg / total_count,
        "event_loss": total_event / total_count,
        "direction_loss": total_direction / total_count,
        "far_hint_loss": total_far_hint / total_count,
    }


