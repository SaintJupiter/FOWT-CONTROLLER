#!/usr/bin/env python3
"""Audit how forecast-source differences propagate to raw 1 Hz pump metrics.

This is intentionally an analysis script only.  It aligns planner-log rows
(10-minute buckets) with the raw timeseries generated by
run_prediction_primary_casebook.py, then reports whether differences in
planner first_action survive target refresh/reuse, safety fallback, and the
actual pump integral.
"""

from __future__ import annotations

import argparse
from pathlib import Path
from typing import Iterable

import numpy as np
import pandas as pd


def parse_run(spec: str) -> tuple[str, Path]:
    if "=" not in spec:
        raise argparse.ArgumentTypeError("run must be LABEL=RUN_DIR")
    label, raw_path = spec.split("=", 1)
    label = label.strip()
    if not label:
        raise argparse.ArgumentTypeError("run label cannot be empty")
    path = Path(raw_path).expanduser()
    if not path.exists():
        raise argparse.ArgumentTypeError(f"run dir not found: {path}")
    return label, path


def infer_case_key(stem: str) -> str:
    marker = "_prediction_primary_"
    if marker in stem:
        return stem.split(marker, 1)[0]
    if "_closed_only" in stem:
        return stem.split("_closed_only", 1)[0]
    return stem


def timeseries_dt_s(df: pd.DataFrame) -> float:
    if "t_s" not in df.columns or len(df) < 2:
        return 1.0
    diffs = np.diff(df["t_s"].to_numpy(dtype=float))
    diffs = diffs[np.isfinite(diffs) & (diffs > 0.0)]
    if diffs.size == 0:
        return 1.0
    return float(np.median(diffs))


def work_m3(series: pd.Series, dt_s: float) -> float:
    vals = np.abs(series.to_numpy(dtype=float))
    if vals.size == 0:
        return 0.0
    return float(np.trapezoid(vals, dx=dt_s) / 60.0)


def p95_abs(series: pd.Series) -> float:
    vals = np.abs(series.to_numpy(dtype=float))
    if vals.size == 0:
        return 0.0
    return float(np.percentile(vals, 95))


def mode_str(series: pd.Series) -> str:
    vals = [str(x) for x in series.dropna().tolist()]
    if not vals:
        return ""
    counts: dict[str, int] = {}
    for val in vals:
        counts[val] = counts.get(val, 0) + 1
    return max(counts.items(), key=lambda kv: (kv[1], kv[0]))[0]


def first_existing(df: pd.DataFrame, names: Iterable[str], default: float = 0.0) -> pd.Series:
    for name in names:
        if name in df.columns:
            return df[name]
    return pd.Series(np.full(len(df), default), index=df.index)


def summarize_timeseries(ts_path: Path, label: str, bucket_s: float) -> pd.DataFrame:
    df = pd.read_csv(ts_path)
    dt_s = timeseries_dt_s(df)
    df["bucket"] = np.floor(df["t_s"].to_numpy(dtype=float) / bucket_s + 1e-9).astype(int)
    refreshed = first_existing(df, ["preview_primary_target_refreshed"])
    reused = first_existing(df, ["preview_primary_target_reused"])
    applied = first_existing(df, ["preview_primary_applied"])
    candidate = first_existing(df, ["preview_primary_candidate_applied"])
    fallback = first_existing(df, ["preview_primary_safety_fallback"])
    active = first_existing(df, ["preview_primary_active"])
    delta = first_existing(df, ["preview_primary_delta_mean_kg"])
    target_age = first_existing(df, ["preview_primary_target_age_s"])
    resumed = first_existing(df, ["preview_primary_target_resumed"])
    target_motion = first_existing(df, ["pump_target_motion_kg_s"])
    backlog = first_existing(df, ["pump_total_backlog_kg"])
    fullspeed = first_existing(df, ["pump_fullspeed_any"])
    action = first_existing(df, ["preview_primary_action"], default=np.nan)
    latch = first_existing(df, ["pump_latch_switch_count"])

    work = df.groupby("bucket")["pump_total_rate_m3_min"].apply(lambda s: work_m3(s, dt_s))
    out = pd.DataFrame({"bucket": work.index, "pump_work_m3": work.to_numpy(dtype=float)})
    grouped = df.assign(
        _refreshed=refreshed,
        _reused=reused,
        _applied=applied,
        _candidate=candidate,
        _fallback=fallback,
        _active=active,
        _delta=delta,
        _target_age=target_age,
        _resumed=resumed,
        _target_motion=target_motion,
        _backlog=backlog,
        _fullspeed=fullspeed,
        _action=action,
        _latch=latch,
    ).groupby("bucket")
    extra = grouped.agg(
        t_start_s=("t_s", "min"),
        t_end_s=("t_s", "max"),
        pitch_abs_p95=("pitch_deg", p95_abs),
        roll_abs_p95=("roll_deg", p95_abs),
        primary_applied_ratio=("_applied", "mean"),
        primary_candidate_ratio=("_candidate", "mean"),
        primary_active_ratio=("_active", "mean"),
        primary_safety_fallback_ratio=("_fallback", "mean"),
        primary_target_refreshed=("_refreshed", "max"),
        primary_target_reused=("_reused", "max"),
        primary_target_resumed=("_resumed", "max"),
        primary_delta_mean_kg=("_delta", "mean"),
        primary_target_age_max_s=("_target_age", "max"),
        pump_target_motion_p95=("_target_motion", lambda s: float(np.percentile(np.abs(s.to_numpy(dtype=float)), 95))),
        pump_backlog_p95_kg=("_backlog", lambda s: float(np.percentile(np.abs(s.to_numpy(dtype=float)), 95))),
        pump_fullspeed_ratio=("_fullspeed", "mean"),
        preview_primary_action_mode=("_action", mode_str),
        latch_switch_count_max=("_latch", "max"),
    ).reset_index()
    out = out.merge(extra, on="bucket", how="left")
    out.insert(0, "run_label", label)
    out.insert(1, "case_key", infer_case_key(ts_path.stem))
    out["timeseries_file"] = str(ts_path)
    return out


def planner_log_for(ts_path: Path) -> Path | None:
    run_dir = ts_path.parents[1]
    planner_dir = run_dir / "planner_logs"
    if not planner_dir.exists():
        return None
    prefix = ts_path.name.removesuffix("_timeseries.csv")
    candidate = planner_dir / f"{prefix}_planner_log.csv"
    if candidate.exists():
        return candidate
    case_key = infer_case_key(ts_path.stem)
    matches = sorted(planner_dir.glob(f"{case_key}*planner_log.csv"))
    return matches[0] if matches else None


def summarize_planner(log_path: Path | None) -> pd.DataFrame:
    if log_path is None:
        return pd.DataFrame()
    df = pd.read_csv(log_path)
    keep = [
        "bucket",
        "first_action",
        "planner_first_action_raw",
        "best_sequence",
        "prediction_primary_target_refreshed",
        "prediction_primary_target_reused",
        "prediction_primary_target_resumed",
        "prediction_primary_hold_target_mode",
        "prediction_primary_target_age_s",
        "prediction_primary_delta_abs_mean_kg",
        "pressure_block0_norm",
        "pressure_block1_norm",
        "pressure_block2_norm",
        "max_envelope_norm",
        "envelope_violation_cost",
        "pump_work_cost",
        "best_scalar_cost",
        "forecast_source",
        "preview_lead_action_active",
        "event_risk_pressure_floor_enabled",
    ]
    cols = [c for c in keep if c in df.columns]
    out = df[cols].copy()
    rename = {c: f"planner_{c}" for c in cols if c != "bucket"}
    out = out.rename(columns=rename)
    out["planner_log_file"] = str(log_path)
    return out


def load_run(label: str, run_dir: Path, bucket_s: float) -> pd.DataFrame:
    ts_dir = run_dir / "timeseries"
    if not ts_dir.exists():
        raise FileNotFoundError(f"missing timeseries dir: {ts_dir}")
    rows: list[pd.DataFrame] = []
    for ts_path in sorted(ts_dir.glob("*prediction_primary*timeseries.csv")):
        ts = summarize_timeseries(ts_path, label, bucket_s)
        log = summarize_planner(planner_log_for(ts_path))
        if not log.empty:
            ts = ts.merge(log, on="bucket", how="left")
        rows.append(ts)
    if not rows:
        raise FileNotFoundError(f"no prediction_primary timeseries in {ts_dir}")
    return pd.concat(rows, ignore_index=True)


def compare_sources(bucket_df: pd.DataFrame) -> pd.DataFrame:
    rows: list[dict[str, object]] = []
    labels = sorted(bucket_df["run_label"].unique())
    for (case_key, bucket), grp in bucket_df.groupby(["case_key", "bucket"], sort=True):
        by_label = {str(r["run_label"]): r for _, r in grp.iterrows()}
        row: dict[str, object] = {"case_key": case_key, "bucket": int(bucket)}
        for label in labels:
            r = by_label.get(label)
            if r is None:
                continue
            row[f"{label}_action"] = r.get("planner_first_action", "")
            row[f"{label}_seq"] = r.get("planner_best_sequence", "")
            row[f"{label}_pump_work_m3"] = float(r.get("pump_work_m3", np.nan))
            row[f"{label}_pitch_p95"] = float(r.get("pitch_abs_p95", np.nan))
            row[f"{label}_roll_p95"] = float(r.get("roll_abs_p95", np.nan))
            row[f"{label}_refreshed"] = float(r.get("primary_target_refreshed", np.nan))
            row[f"{label}_reused"] = float(r.get("primary_target_reused", np.nan))
            row[f"{label}_resumed"] = float(r.get("primary_target_resumed", np.nan))
            row[f"{label}_delta_kg"] = float(r.get("primary_delta_mean_kg", np.nan))
            row[f"{label}_fallback_ratio"] = float(r.get("primary_safety_fallback_ratio", np.nan))
            row[f"{label}_target_motion_p95"] = float(r.get("pump_target_motion_p95", np.nan))
            row[f"{label}_backlog_p95_kg"] = float(r.get("pump_backlog_p95_kg", np.nan))
        for a, b in [("learned", "persistence"), ("oracle", "persistence"), ("learned", "oracle")]:
            if a in by_label and b in by_label:
                ra, rb = by_label[a], by_label[b]
                row[f"{a}_minus_{b}_pump_m3"] = float(ra["pump_work_m3"] - rb["pump_work_m3"])
                row[f"{a}_minus_{b}_pitch_p95"] = float(ra["pitch_abs_p95"] - rb["pitch_abs_p95"])
                row[f"{a}_minus_{b}_roll_p95"] = float(ra["roll_abs_p95"] - rb["roll_abs_p95"])
                row[f"{a}_vs_{b}_same_planner_action"] = int(
                    str(ra.get("planner_first_action", "")) == str(rb.get("planner_first_action", ""))
                )
        rows.append(row)
    return pd.DataFrame(rows)


def markdown_table(df: pd.DataFrame, floatfmt: str = ".3f") -> str:
    if df.empty:
        return "_none_"
    cols = [str(c) for c in df.columns]
    lines = [
        "| " + " | ".join(cols) + " |",
        "| " + " | ".join(["---"] * len(cols)) + " |",
    ]
    for _, row in df.iterrows():
        vals: list[str] = []
        for col in df.columns:
            val = row[col]
            if isinstance(val, (float, np.floating)):
                if np.isfinite(float(val)):
                    vals.append(format(float(val), floatfmt))
                else:
                    vals.append("")
            else:
                vals.append(str(val))
        lines.append("| " + " | ".join(vals) + " |")
    return "\n".join(lines)


def report(bucket_df: pd.DataFrame, compare_df: pd.DataFrame, out_dir: Path) -> str:
    lines: list[str] = []
    lines.append("# Prediction Signal Flow Audit")
    lines.append("")
    lines.append("Aligns 10-minute planner buckets with raw 1 Hz timeseries pump and attitude metrics.")
    lines.append("")
    lines.append(f"- bucket rows: `{len(bucket_df)}`")
    lines.append(f"- cases: `{bucket_df['case_key'].nunique()}`")
    lines.append(f"- run labels: `{', '.join(sorted(bucket_df['run_label'].unique()))}`")
    lines.append("")

    lines.append("## Case Totals")
    totals = (
        bucket_df.groupby(["case_key", "run_label"], sort=True)
        .agg(
            pump_work_m3=("pump_work_m3", "sum"),
            pitch_abs_p95=("pitch_abs_p95", "max"),
            roll_abs_p95=("roll_abs_p95", "max"),
            refreshed_buckets=("primary_target_refreshed", "sum"),
            reused_buckets=("primary_target_reused", "sum"),
            fallback_ratio=("primary_safety_fallback_ratio", "mean"),
        )
        .reset_index()
    )
    lines.append(markdown_table(totals, floatfmt=".3f"))
    lines.append("")

    if {"learned_action", "persistence_action"}.issubset(compare_df.columns):
        lp = compare_df.dropna(subset=["learned_action", "persistence_action"], how="any")
        diff = lp[lp["learned_vs_persistence_same_planner_action"] == 0]
        washed = diff[np.abs(diff["learned_minus_persistence_pump_m3"]) <= 1.0]
        lines.append("## Learned vs Persistence")
        lines.append("")
        lines.append(f"- planner action differs in `{len(diff)}` / `{len(lp)}` aligned buckets.")
        lines.append(
            f"- action differs but bucket pump difference <= 1 m3 in `{len(washed)}` buckets."
        )
        if not diff.empty:
            show_cols = [
                "case_key",
                "bucket",
                "learned_action",
                "persistence_action",
                "learned_pump_work_m3",
                "persistence_pump_work_m3",
                "learned_minus_persistence_pump_m3",
                "learned_minus_persistence_pitch_p95",
                "learned_minus_persistence_roll_p95",
            ]
            lines.append("")
            lines.append(markdown_table(diff[show_cols], floatfmt=".3f"))
            lines.append("")

    lines.append("## Files")
    lines.append("")
    lines.append(f"- bucket flow: `{out_dir / 'prediction_signal_flow_buckets.csv'}`")
    lines.append(f"- source compare: `{out_dir / 'prediction_signal_flow_source_compare.csv'}`")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--run", action="append", type=parse_run, required=True, help="LABEL=RUN_DIR")
    parser.add_argument("--out-dir", required=True)
    parser.add_argument("--bucket-s", type=float, default=600.0)
    args = parser.parse_args()

    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    bucket_rows = [load_run(label, path, args.bucket_s) for label, path in args.run]
    bucket_df = pd.concat(bucket_rows, ignore_index=True)
    compare_df = compare_sources(bucket_df)
    bucket_df.to_csv(out_dir / "prediction_signal_flow_buckets.csv", index=False)
    compare_df.to_csv(out_dir / "prediction_signal_flow_source_compare.csv", index=False)
    (out_dir / "prediction_signal_flow_report.md").write_text(
        report(bucket_df, compare_df, out_dir),
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
