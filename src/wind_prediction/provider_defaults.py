@dataclass(frozen=True)
class ProviderOptions:
    values: Mapping[str, Any]

    def __getattr__(self, name: str) -> Any:
        try:
            return self.values[name]
        except KeyError as exc:
            raise AttributeError(name) from exc


def normalize_provider_options(options: Mapping[str, Any]) -> ProviderOptions:
    unknown = sorted(set(options) - set(LEGACY_PROVIDER_DEFAULTS))
    if unknown:
        raise TypeError(f"unknown provider options: {unknown}")
    merged = dict(LEGACY_PROVIDER_DEFAULTS)
    merged.update(options)
    return ProviderOptions(MappingProxyType(merged))
